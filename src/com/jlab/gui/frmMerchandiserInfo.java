    public void SaveMercInfo() {

        try {
            String query = "insert into tblMerchandiserInfo(MerchID,MerchName,Address,Phone,Email,Remarks) values (?,?,?,?,?,?)";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, txtMerchID.getText());
            pst.setString(2, txtMerchName.getText());
            pst.setString(3, txtAddress.getText());
            pst.setString(4, txtTelephone.getText());
            pst.setString(5, txtEmail.getText());
            pst.setString(6, txtRemarks.getText());
            pst.execute();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }


