    //show / add the the data to table
    public ArrayList<MerchandiserInfo_Bean> getAllData() {
        ArrayList<MerchandiserInfo_Bean> al = null;
        al = new ArrayList<MerchandiserInfo_Bean>();
        try {

            String qry = "select * from tblMerchandiserInfo";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            MerchandiserInfo_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new MerchandiserInfo_Bean(rs.getString("MerchID"), rs.getString("MerchName"),
                        rs.getString("Phone"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void fillTable() {
        ArrayList<MerchandiserInfo_Bean> al = getAllData();
        DefaultTableModel model = (DefaultTableModel) tblBank.getModel();
        //  tblChequeDetails.getColumnModel().getColumn(0).setPreferredWidth(10);
        model.setRowCount(0); // Empty/clear the table
        Object[] row = new Object[3];
        for (int i = 0; i < al.size(); i++) {
            row[0] = al.get(i).getId();
            row[1] = al.get(i).getName();
            row[2] = al.get(i).getPhone();
            model.addRow(row);

        }
    }

    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(MerchID) AS MaxID FROM tblMerchandiserInfo");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtMerchID.setText("MCD-00001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtMerchID.setText("MCD-" + String.format("%05d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

