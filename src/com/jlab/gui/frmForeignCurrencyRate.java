    public ArrayList<Currency_Bean> getAllData() {
        ArrayList<Currency_Bean> al = null;
        al = new ArrayList<Currency_Bean>();
        try {

            String qry = "select * from tblCurrencyInfo";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            Currency_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new Currency_Bean(rs.getString("CurrencyID"), rs.getString("CurrencyName"), rs.getString("Realized"), rs.getString("BTB"),
                        rs.getString("BillPur"), rs.getString("ExpSales"), rs.getString("Transfer"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void fillTable() {
        ArrayList<Currency_Bean> al = getAllData();
        DefaultTableModel model = (DefaultTableModel) tblunit.getModel();
        //  tblChequeDetails.getColumnModel().getColumn(0).setPreferredWidth(10);
        model.setRowCount(0); // Empty/clear the table
        Object[] row = new Object[7];
        for (int i = 0; i < al.size(); i++) {
            row[0] = al.get(i).getCurrId();
            row[1] = al.get(i).getCurrName();
            row[2] = al.get(i).getRealized();
            row[3] = al.get(i).getBtbAdj();
            row[4] = al.get(i).getBillPur();
            row[5] = al.get(i).getExeSales();
            row[6] = al.get(i).getTransfer();
            model.addRow(row);

        }
    }

    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(CurrencyID) AS MaxID FROM tblCurrencyInfo");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtCurrID.setText("CUR-001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtCurrID.setText("CUR-" + String.format("%03d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

    public void ShowLocal() {

        Calendar ca = new GregorianCalendar();
        String day = ca.get(Calendar.DAY_OF_MONTH) + "";
        String month = ca.get(Calendar.MONTH) + 1 + "";
        String year = ca.get(Calendar.YEAR) + "";

        if (day.length() == 1) {
            day = "0" + day;
        }
        if (month.length() == 1) {
            month = "0" + month;
        }

        String dd = day + " " + month + " " + year;
        Date date = null;
        try {
            date = new SimpleDateFormat("dd MM yyyy").parse(dd);
        } catch (ParseException ex) {

        }
        dtDate.setDate(date);

    }

