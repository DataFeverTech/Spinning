// ---------- ID ----------
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(WorkOrderNo) AS MaxID FROM tblWorkOrder");
            r.next();
            if (r.getString("MaxID") == null) {
                txtWONo.setText("WO-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(3));
                id++;
                txtWONo.setText("WO-" + String.format("%07d", id));
            }
            txtWONo.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

