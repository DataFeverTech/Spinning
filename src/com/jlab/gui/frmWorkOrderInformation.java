    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblWorkOrder "
                + "(WorkOrderNo, WODate, Party, PartyPO, DeliveryDate, Currency, MarketedBy, Remarks, TotalQty, TotalAmount) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtWONo.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, notSel(cboParty) ? "" : sel(cboParty));
        p.setString(4, txtPartyPO.getText());
        p.setDate(5, sqlDate(dtDelivaryDate));
        p.setString(6, notSel(cboCurrency) ? "" : sel(cboCurrency));
        p.setString(7, notSel(cboMarketedBy) ? "" : sel(cboMarketedBy));
        p.setString(8, txtRemarks.getText());
        p.setString(9, txtTotalQty.getText());
        p.setString(10, txtTotalAmount.getText());
        p.executeUpdate();
        p.close();
    }

    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblWorkOrderDetail "
                + "(WorkOrderNo, SL, YarnCount, YarnType, Composition, Packing, Qty, UnitPrice, Amount) "
                + "VALUES (?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblWorkOrderInformation.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtWONo.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            p.setString(3, model.getValueAt(i, 1).toString());
            p.setString(4, model.getValueAt(i, 2).toString());
            p.setString(5, model.getValueAt(i, 3).toString());
            p.setString(6, model.getValueAt(i, 4).toString());
            p.setString(7, model.getValueAt(i, 5).toString());
            p.setString(8, model.getValueAt(i, 6).toString());
            p.setString(9, model.getValueAt(i, 7).toString());
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }

    // ---------- Helpers ----------
    private double num(String s) {
        try {
            return Double.parseDouble(s.trim());
        } catch (Exception e) {
            return 0;
        }
    }

    private java.sql.Date sqlDate(com.toedter.calendar.JDateChooser dc) {
        return dc.getDate() == null ? null : new java.sql.Date(dc.getDate().getTime());
    }

    private String sel(javax.swing.JComboBox<String> c) {
        Object o = c.getSelectedItem();
        return o == null ? "" : o.toString();
    }

    private boolean notSel(javax.swing.JComboBox<String> c) {
        String s = sel(c);
        return s.equals("") || s.startsWith("Select");
    }

// ---------- Fill Combo ----------
    private void FillCombo(javax.swing.JComboBox<String> cbo, String query, String col, String placeholder) {
        try {
            cbo.removeAllItems();
            cbo.addItem(placeholder);
            PreparedStatement p = con.prepareStatement(query);
            ResultSet r = p.executeQuery();
            while (r.next()) {
                cbo.addItem(r.getString(col));
            }
            r.close();
            p.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

