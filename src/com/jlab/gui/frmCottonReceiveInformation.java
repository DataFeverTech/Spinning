    private void cboImportLCPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboImportLCPopupMenuWillBecomeInvisible
        txtSupplier.setText("");
        txtOrigin.setText("");
        txtLCBales.setText("");
        if (notSel(cboImportLC)) {
            return;
        }
        try {
            PreparedStatement p = con.prepareStatement("SELECT Supplier, Origin, LCBales FROM tblImportLC WHERE ImportLC=?");
            p.setString(1, sel(cboImportLC));
            ResultSet r = p.executeQuery();
            if (r.next()) {
                txtSupplier.setText(r.getString("Supplier"));
                txtOrigin.setText(r.getString("Origin"));
                txtLCBales.setText(r.getString("LCBales"));
            }
            r.close();
            p.close();
            CalcTotal();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboImportLCPopupMenuWillBecomeInvisible

