    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblCottonReceive "
                + "(ReceiveId, ReceiveDate, ImportLC, Supplier, BLNo, DeliveryDate, BENo, Origin, ChalanNo, TruckNo, Godown, "
                + "LCBales, Received, Balance, Remarks, TotalBales, TotalNetWt, TotalShort) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtReceiveId.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, notSel(cboImportLC) ? "" : sel(cboImportLC));
        p.setString(4, txtSupplier.getText());
        p.setString(5, txtBLNo.getText());
        p.setDate(6, sqlDate(dtDelivaryDate));
        p.setString(7, txtBENo.getText());
        p.setString(8, txtOrigin.getText());
        p.setString(9, txtChalanNo.getText());
        p.setString(10, txtTruckNo.getText());
        p.setString(11, notSel(cboGodown) ? "" : sel(cboGodown));
        p.setString(12, txtLCBales.getText());
        p.setString(13, txtReceived.getText());
        p.setString(14, txtBalance.getText());
        p.setString(15, txtRemarks.getText());
        p.setString(16, txtTotalQty.getText());
        p.setString(17, txtTotalAmount.getText());
        p.setString(18, txtTotalAmount1.getText());
        p.executeUpdate();
        p.close();
    }

    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblCottonReceiveDetail "
                + "(ReceiveId, SL, LotNo, Container, Bales, GrossWt, TareWt, NetWt, InvoiceWt, ShortWt, Moisture) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblCottonReceiveInformation.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtReceiveId.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            for (int c = 1; c <= 9; c++) {
                p.setString(c + 2, String.valueOf(model.getValueAt(i, c)));
            }
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }
    // ---------- Helpers ----------

    private double num(String s) {
        try {
            return Double.parseDouble(s.trim());
        } catch (Exception e) {
            return 0;
        }
    }

    private java.sql.Date sqlDate(com.toedter.calendar.JDateChooser dc) {
        return dc.getDate() == null ? null : new java.sql.Date(dc.getDate().getTime());
    }

    private String sel(javax.swing.JComboBox<String> c) {
        Object o = c.getSelectedItem();
        return o == null ? "" : o.toString();
    }

    private boolean notSel(javax.swing.JComboBox<String> c) {
        String s = sel(c);
        return s.equals("") || s.startsWith("Select");
    }

// ---------- Fill Combo ----------
    private void FillCombo(javax.swing.JComboBox<String> cbo, String query, String col) {
        try {
            cbo.removeAllItems();
            cbo.addItem("Select Product Info");
            PreparedStatement p = con.prepareStatement(query);
            ResultSet r = p.executeQuery();
            while (r.next()) {
                cbo.addItem(r.getString(col));
            }
            r.close();
            p.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

    public void Fill_ImportLC() {
        FillCombo(cboImportLC, "SELECT DISTINCT ImportLC FROM tblImportLC ORDER BY ImportLC", "ImportLC");
    }

    public void Fill_Godown() {
        FillCombo(cboGodown, "SELECT DISTINCT GodownName FROM tblGodown ORDER BY GodownName", "GodownName");
    }

    // ---------- ID ----------
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(ReceiveId) AS MaxID FROM tblCottonReceive");
            r.next();
            if (r.getString("MaxID") == null) {
                txtReceiveId.setText("CR-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(3));
                id++;
                txtReceiveId.setText("CR-" + String.format("%07d", id));
            }
            txtReceiveId.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

