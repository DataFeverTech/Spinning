        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtReqId.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, selOrEmpty(cboDepartment));
        p.setDate(4, sqlDate(dtReqDate));
        p.setString(5, txtReqId1.getText());
        p.setString(6, txtReqId2.getText());
        p.setString(7, selOrEmpty(cboShift));
        p.setString(8, selOrEmpty(cboShift1));
        p.setString(9, selOrEmpty(cboWorkOrder));
