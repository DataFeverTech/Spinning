    private double[] sum2(String table, String balesCol, String wtCol, String lot) throws Exception {
        PreparedStatement p = con.prepareStatement(
                "SELECT ISNULL(SUM(CAST(" + balesCol + " AS FLOAT)),0) AS B, "
                + "ISNULL(SUM(CAST(" + wtCol + " AS FLOAT)),0) AS W FROM " + table + " WHERE LotNo=?");
        p.setString(1, lot);
        ResultSet r = p.executeQuery();
        double[] v = new double[]{0, 0};
        if (r.next()) {
            v[0] = r.getDouble("B");
            v[1] = r.getDouble("W");
        }
        r.close();
        p.close();
        return v;
    }

// grid-এ একই Lot এর আগের যোগফল
    private double gridSum(String lot, int col) {
        DefaultTableModel model = (DefaultTableModel) tblRequistionForCotton.getModel();
        double s = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            if (String.valueOf(model.getValueAt(i, 3)).equals(lot)) {
                s += num(String.valueOf(model.getValueAt(i, col)));
            }
        }
        return s;
    }

// ---------- ID ----------
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(IssueId) AS MaxID FROM tblCottonIssue");
            r.next();
            if (r.getString("MaxID") == null) {
                txtReqId.setText("CIS-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(4));
                id++;
                txtReqId.setText("CIS-" + String.format("%07d", id));
            }
            txtReqId.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

