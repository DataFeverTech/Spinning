    private void CalcTotal() {
        DefaultTableModel model = (DefaultTableModel) tblRequistionForCotton.getModel();
        double bales = 0, wt = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            bales += num(String.valueOf(model.getValueAt(i, 8)));
            wt += num(String.valueOf(model.getValueAt(i, 9)));
        }
        txtTotalBales.setText(String.format("%.0f", bales));
        txtTotalBales1.setText(String.format("%.2f", wt));
    }

