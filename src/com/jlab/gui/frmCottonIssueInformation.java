// ---------- Grid Add ----------
    public void GridAdd() {
        if (notSel(cboDepartment) || notSel(cboWorkOrder)) {
            JOptionPane.showMessageDialog(this, "Select Requisition & Work Order");
            return;
        }
        if (notSel(cboLot)) {
            JOptionPane.showMessageDialog(this, "Select Lot No");
            return;
        }
        if (txtAlreadyReq.getText().trim().isEmpty() || txtBalance.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Issue Bales & Issue Wt");
            return;
        }
        String lot = sel(cboLot);
        if (num(txtAlreadyReq.getText()) + gridSum(lot, 8) > num(txtProcessLoss.getText())) {
            JOptionPane.showMessageDialog(this, "Issue Bales cannot be more than Available Bales");
            return;
        }
        if (num(txtBalance.getText()) + gridSum(lot, 9) > num(txtCottonReq.getText())) {
            JOptionPane.showMessageDialog(this, "Issue Wt cannot be more than Available Wt");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblRequistionForCotton.getModel();
        model.addRow(new Object[]{
            model.getRowCount() + 1,
            sel(cboWorkOrder),
            txtYarnCount1.getText(),
            lot,
            txtBuyer.getText(),
            txtYarnCount.getText(),
            txtYarnQty.getText(),
            txtYarnQty2.getText(),
            txtAlreadyReq.getText(),
            txtBalance.getText()
        });

        CalcTotal();
        ClearProductFields();
    }

