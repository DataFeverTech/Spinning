    private void cboLotPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboLotPopupMenuWillBecomeInvisible
        txtBuyer.setText("");
        txtYarnCount.setText("");
        txtYarnQty.setText("");
        txtYarnQty2.setText("");
        txtProcessLoss.setText("");
        txtCottonReq.setText("");
        if (notSel(cboLot)) {
            return;
        }
        String lot = sel(cboLot);
        try {
            PreparedStatement p = con.prepareStatement(
                    "SELECT TOP 1 r.ImportLC, r.Origin, r.Godown FROM tblCottonReceive r "
                    + "INNER JOIN tblCottonReceiveDetail d ON d.ReceiveId = r.ReceiveId WHERE d.LotNo=?");
            p.setString(1, lot);
            ResultSet r = p.executeQuery();
            if (r.next()) {
                txtBuyer.setText(r.getString("ImportLC"));    // Import L/C
                txtYarnCount.setText(r.getString("Origin"));  // Origin
                txtYarnQty.setText(r.getString("Godown"));    // Godown
            }
            r.close();
            p.close();

            p = con.prepareStatement("SELECT TOP 1 Mic FROM tblCottonLabTestDetail WHERE LotNo=? ORDER BY ReceiveId DESC");
            p.setString(1, lot);
            r = p.executeQuery();
            if (r.next()) {
                txtYarnQty2.setText(r.getString("Mic"));
            }
            r.close();
            p.close();

            double[] rec = sum2("tblCottonReceiveDetail", "Bales", "NetWt", lot);
            double[] iss = sum2("tblCottonIssueDetail", "IssueBales", "IssueWt", lot);
            double[] ret = sum2("tblCottonReturnDetail", "ReturnBales", "ReturnWt", lot);
            txtProcessLoss.setText(String.format("%.0f", rec[0] - iss[0] + ret[0]));  // Avl Bales
            txtCottonReq.setText(String.format("%.2f", rec[1] - iss[1] + ret[1]));    // Avl Wt
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboLotPopupMenuWillBecomeInvisible

