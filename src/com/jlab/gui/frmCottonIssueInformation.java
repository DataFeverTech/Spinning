    private void cboDepartmentPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboDepartmentPopupMenuWillBecomeInvisible
        dtReqDate.setDate(null);
        txtReqId1.setText("");
        txtReqId2.setText("");
        cboShift.setSelectedIndex(0);
        ClearReqItemFields();
        if (notSel(cboDepartment)) {
            return;
        }
        try {
            PreparedStatement p = con.prepareStatement(
                    "SELECT RequiredDate, Department, RequestedBy, Store FROM tblCottonRequisition WHERE ReqId=?");
            p.setString(1, sel(cboDepartment));
            ResultSet r = p.executeQuery();
            if (r.next()) {
                dtReqDate.setDate(r.getDate("RequiredDate"));
                txtReqId1.setText(r.getString("Department"));
                txtReqId2.setText(r.getString("RequestedBy"));
                cboShift.setSelectedItem(r.getString("Store"));
            }
            r.close();
            p.close();

            // এই requisition-এর Work Order গুলো
            p = con.prepareStatement("SELECT DISTINCT WorkOrder FROM tblCottonRequisitionDetail WHERE ReqId=?");
            p.setString(1, sel(cboDepartment));
            r = p.executeQuery();
            while (r.next()) {
                cboWorkOrder.addItem(r.getString("WorkOrder"));
            }
            r.close();
            p.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboDepartmentPopupMenuWillBecomeInvisible

