    public void percentic() {

        String rawTotalSale = txtValue.getText();
        String rawTotalPaid = txtPercenNeg.getText();

        Double sale = Double.parseDouble(rawTotalSale);
        Double paid = Double.parseDouble(rawTotalPaid);

        Double total = (sale * paid / 100);

        txtNegotition.setText("" + total);
        txtTotalNegUsd.setText("" + total);

        String rawTotalSale1 = txtTotalTK.getText();
        String rawTotalPaid1 = txtBITK.getText();

        Double sale1 = Double.parseDouble(rawTotalSale1);
        Double paid1 = Double.parseDouble(rawTotalPaid1);

        Double total12 = (sale1 + paid1);

        txtTKNeg.setText("" + total12);

    }

