    public void SubmitForeignBillNegProduct() {

        try {

            int rows = tblForeignBillNeg.getRowCount();
            //       con.setAutoCommit(false);
            String query = "Insert into tblExportBillProduct(ExportBillNo,InvoiceNo,Quantity,Unit,Price,Value,TotalVal) values (?,?,?,?,?,?,?)";
            PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
            for (int row = 0; row < rows; row++) {

                String BankAccount = (String) tblForeignBillNeg.getValueAt(row, 0);
                String Percent = (String) tblForeignBillNeg.getValueAt(row, 1);
                String Value = (String) tblForeignBillNeg.getValueAt(row, 2);
                String Rate = (String) tblForeignBillNeg.getValueAt(row, 3);
                String TotalValue = (String) tblForeignBillNeg.getValueAt(row, 4);

                pst.setString(1, txtForeignBillID.getText());
                pst.setString(2, BankAccount);
                pst.setString(3, Percent);
                pst.setString(4, Value);
                pst.setString(5, Rate);
                pst.setString(6, TotalValue);

                pst.addBatch();

            }

            pst.executeBatch();
            //     con.commit();
            //JOptionPane.showMessageDialog(null, "Saved!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }

    }


