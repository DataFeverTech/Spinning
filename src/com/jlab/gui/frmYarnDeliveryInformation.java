// Yarn Count select: Order Qty, Delivered, Balance
// ---------- Auto Calc: Net = Bags x Kg/Bag, Gross = Net (দরকারে বদলান) ----------
    private void CalcWeight() {
        double net = num(txtBags.getText()) * num(txtKgBag.getText());
        txtNetWt.setText(String.format("%.2f", net));
        txtGrossWt.setText(String.format("%.2f", net));
    }

// grid-এ একই Yarn Count এর আগের Net Wt যোগফল
    private double gridNetSum(String yarn) {
        DefaultTableModel model = (DefaultTableModel) tblYarnDeliveryInformation.getModel();
        double s = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            if (String.valueOf(model.getValueAt(i, 1)).equals(yarn)) {
                s += num(String.valueOf(model.getValueAt(i, 5)));
            }
        }
        return s;
    }

// ---------- ID ----------
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(DeliveryNo) AS MaxID FROM tblYarnDelivery");
            r.next();
            if (r.getString("MaxID") == null) {
                txtDelivaryNo.setText("YD-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(3));
                id++;
                txtDelivaryNo.setText("YD-" + String.format("%07d", id));
            }
            txtDelivaryNo.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

