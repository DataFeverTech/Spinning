    private void cboWorkOrderPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboWorkOrderPopupMenuWillBecomeInvisible
        txtParty.setText("");
        txtPartyPO.setText("");
        dtDueDate.setDate(null);
        ClearYarnFields();
        if (notSel(cboWorkOrder)) {
            return;
        }
        try {
            PreparedStatement p = con.prepareStatement(
                    "SELECT Party, PartyPO, DeliveryDate FROM tblWorkOrder WHERE WorkOrderNo=?");
            p.setString(1, sel(cboWorkOrder));
            ResultSet r = p.executeQuery();
            if (r.next()) {
                txtParty.setText(r.getString("Party"));
                txtPartyPO.setText(r.getString("PartyPO"));
                dtDueDate.setDate(r.getDate("DeliveryDate"));
            }
            r.close();
            p.close();

            // এই Work Order এর Yarn Count গুলো
            p = con.prepareStatement("SELECT DISTINCT YarnCount FROM tblWorkOrderDetail WHERE WorkOrderNo=?");
            p.setString(1, sel(cboWorkOrder));
            r = p.executeQuery();
            while (r.next()) {
                cboYarnCount.addItem(r.getString("YarnCount"));
            }
            r.close();
            p.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboWorkOrderPopupMenuWillBecomeInvisible

