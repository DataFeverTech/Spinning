// ---------- Grid Add ----------
    public void GridAdd() {
        if (notSel(cboWorkOrder)) {
            JOptionPane.showMessageDialog(this, "Select Work Order");
            return;
        }
        if (notSel(cboYarnCount)) {
            JOptionPane.showMessageDialog(this, "Select Yarn Count");
            return;
        }
        if (txtBags.getText().trim().isEmpty() || txtKgBag.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Bags & Kg/Bag");
            return;
        }
        String yarn = sel(cboYarnCount);
        double net = num(txtNetWt.getText());
        double balance = num(txtBalance.getText()) - gridNetSum(yarn) - net;
        if (balance < 0) {
            JOptionPane.showMessageDialog(this, "Net Wt cannot be more than Balance");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblYarnDeliveryInformation.getModel();
        model.addRow(new Object[]{
            model.getRowCount() + 1,
            yarn,
            txtEndUse.getText(),
            txtLotNo.getText(),
            txtBags.getText(),
            txtNetWt.getText(),
            txtGrossWt.getText(),
            String.format("%.2f", balance)
        });

        CalcTotal();
        ClearProductFields();
    }

    private void ClearProductFields() {
        cboYarnCount.setSelectedIndex(0);
        txtEndUse.setText("");
        txtLotNo.setText("");
        txtOrderQty.setText("");
        txtDelivared.setText("");
        txtBalance.setText("");
        txtAvlBales.setText("");
        txtBags.setText("");
        txtKgBag.setText("");
        txtNetWt.setText("");
        txtGrossWt.setText("");
    }

    private void CalcTotal() {
        DefaultTableModel model = (DefaultTableModel) tblYarnDeliveryInformation.getModel();
        double bags = 0, net = 0, gross = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            bags += num(String.valueOf(model.getValueAt(i, 4)));
            net += num(String.valueOf(model.getValueAt(i, 5)));
            gross += num(String.valueOf(model.getValueAt(i, 6)));
        }
        txtTotalBags.setText(String.format("%.0f", bags));
        txtTotalNetWt.setText(String.format("%.2f", net));
        txtTotalGrossWt.setText(String.format("%.2f", gross));
    }



// ---------- Save General ----------
    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblYarnDelivery "
                + "(DeliveryNo, DeliveryDate, WorkOrder, Party, PartyPO, ChalanNo, GatePass, DeliveryTo, DueDate, "
                + "VehicleNo, Driver, Mobile, DeliveredBy, Remarks, TotalBags, TotalNetWt, TotalGrossWt) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtDelivaryNo.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, selOrEmpty(cboWorkOrder));
        p.setString(4, txtParty.getText());
        p.setString(5, txtPartyPO.getText());
        p.setString(6, txtChalanNo.getText());
        p.setString(7, txtGatePass.getText());
        p.setString(8, txtDelivaryTo.getText());
        p.setDate(9, sqlDate(dtDueDate));
        p.setString(10, txtVahicleNo.getText());
        p.setString(11, txtDrive.getText());
        p.setString(12, txtMobile.getText());
        p.setString(13, selOrEmpty(cboDeliveredBy));
        p.setString(14, txtRemarks.getText());
        p.setString(15, txtTotalBags.getText());
        p.setString(16, txtTotalNetWt.getText());
        p.setString(17, txtTotalGrossWt.getText());
        p.executeUpdate();
        p.close();
    }

// ---------- Save Products ----------
    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblYarnDeliveryDetail "
                + "(DeliveryNo, SL, WorkOrder, YarnCount, EndUse, LotNo, Bags, NetWt, GrossWt, Balance) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblYarnDeliveryInformation.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtDelivaryNo.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            p.setString(3, selOrEmpty(cboWorkOrder));
            for (int c = 1; c <= 7; c++) {
                p.setString(c + 3, String.valueOf(model.getValueAt(i, c)));
            }
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }

