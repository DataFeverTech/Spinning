    private void cboYarnCountPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboYarnCountPopupMenuWillBecomeInvisible
        txtOrderQty.setText("");
        txtDelivared.setText("");
        txtBalance.setText("");
        if (notSel(cboYarnCount) || notSel(cboWorkOrder)) {
            return;
        }
        try {
            double order = 0, delivered = 0;
            PreparedStatement p = con.prepareStatement(
                    "SELECT ISNULL(SUM(CAST(Qty AS FLOAT)),0) AS Q FROM tblWorkOrderDetail WHERE WorkOrderNo=? AND YarnCount=?");
            p.setString(1, sel(cboWorkOrder));
            p.setString(2, sel(cboYarnCount));
            ResultSet r = p.executeQuery();
            if (r.next()) {
                order = r.getDouble("Q");
            }
            r.close();
            p.close();

            p = con.prepareStatement(
                    "SELECT ISNULL(SUM(CAST(NetWt AS FLOAT)),0) AS D FROM tblYarnDeliveryDetail WHERE WorkOrder=? AND YarnCount=?");
            p.setString(1, sel(cboWorkOrder));
            p.setString(2, sel(cboYarnCount));
            r = p.executeQuery();
            if (r.next()) {
                delivered = r.getDouble("D");
            }
            r.close();
            p.close();

            txtOrderQty.setText(String.format("%.2f", order));
            txtDelivared.setText(String.format("%.2f", delivered));
            txtBalance.setText(String.format("%.2f", order - delivered));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboYarnCountPopupMenuWillBecomeInvisible

