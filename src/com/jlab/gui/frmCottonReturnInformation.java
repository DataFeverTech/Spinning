    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblCottonReturn "
                + "(ReturnId, ReturnDate, IssueNo, IssueDate, Department, WorkOrder, YarnCount, ReturnedBy, ReceivedBy, "
                + "Remarks, TotalBales, TotalWt) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtReceiveId.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, selOrEmpty(cboIssuedNo));
        p.setDate(4, sqlDate(dtIssueDate));
        p.setString(5, txtDepartMent.getText());
        p.setString(6, txtWorkOrder.getText());
        p.setString(7, txtYarnCount.getText());
        p.setString(8, selOrEmpty(cboReturnBy));
        p.setString(9, selOrEmpty(cboReceiveBy));
        p.setString(10, txtRemarks.getText());
        p.setString(11, txtTotalBales.getText());
        p.setString(12, txtTotaWt.getText());
        p.executeUpdate();
        p.close();
    }

    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblCottonReturnDetail "
                + "(ReturnId, SL, LotNo, ImportLC, Origin, IssuedBales, IssuedWt, ReturnBales, ReturnWt, Condition, Godown) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblCottonLabTestInformation.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtReceiveId.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            for (int c = 1; c <= 9; c++) {
                p.setString(c + 2, String.valueOf(model.getValueAt(i, c)));
            }
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }

