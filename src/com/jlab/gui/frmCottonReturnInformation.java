// ---------- Grid Add ----------
    public void GridAdd() {
        if (notSel(cboLotNo)) {
            JOptionPane.showMessageDialog(this, "Select Lot No");
            return;
        }
        if (txtReturnBales.getText().trim().isEmpty() || txtReturnWt.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Return Bales & Return Wt");
            return;
        }
        if (num(txtReturnBales.getText()) > num(txtIssued.getText())) {
            JOptionPane.showMessageDialog(this, "Return Bales cannot be more than Issued");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblCottonLabTestInformation.getModel();
        model.addRow(new Object[]{
            model.getRowCount() + 1,
            sel(cboLotNo),
            txtImportLC.getText(),
            txtOrigin.getText(),
            txtIssued.getText(),
            txtIssuedWt.getText(),
            txtReturnBales.getText(),
            txtReturnWt.getText(),
            selOrEmpty(cboCondition),
            selOrEmpty(cboGodown)
        });

        CalcTotal();
        ClearProductFields();
    }

    private void ClearProductFields() {
        cboLotNo.setSelectedIndex(0);
        if (cboCondition.getItemCount() > 0) {
            cboCondition.setSelectedIndex(0);
        }
        if (cboGodown.getItemCount() > 0) {
            cboGodown.setSelectedIndex(0);
        }
        txtImportLC.setText("");
        txtOrigin.setText("");
        txtIssued.setText("");
        txtIssuedWt.setText("");
        txtReturnBales.setText("");
        txtReturnWt.setText("");
    }

    private void CalcTotal() {
        DefaultTableModel model = (DefaultTableModel) tblCottonLabTestInformation.getModel();
        double bales = 0, wt = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            bales += num(String.valueOf(model.getValueAt(i, 6)));
            wt += num(String.valueOf(model.getValueAt(i, 7)));
        }
        txtTotalBales.setText(String.format("%.0f", bales));
        txtTotaWt.setText(String.format("%.2f", wt));
    }

    private void Reset() {
        cboIssuedNo.setSelectedIndex(0);
        cboReturnBy.setSelectedIndex(0);
        cboReceiveBy.setSelectedIndex(0);
        dtIssueDate.setDate(null);
        txtDepartMent.setText("");
        txtWorkOrder.setText("");
        txtYarnCount.setText("");
        txtRemarks.setText("");
        txtTotalBales.setText("");
        txtTotaWt.setText("");
        ClearProductFields();
        ((DefaultTableModel) tblCottonLabTestInformation.getModel()).setRowCount(0);
        GenAutoID();
        ShowLocal();
    }


