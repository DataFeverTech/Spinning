    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed

        if (tblYarnReturnInformation.getSelectionModel().isSelectionEmpty()) {
            JOptionPane.showMessageDialog(null, "Nother Selected");
        } else {
            DefaultTableModel model = (DefaultTableModel) tblYarnReturnInformation.getModel();
            try {
                int SelectedRowIndex = tblYarnReturnInformation.getSelectedRow();
                model.removeRow(SelectedRowIndex);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }

        }
    }//GEN-LAST:event_btnRemoveActionPerformed

