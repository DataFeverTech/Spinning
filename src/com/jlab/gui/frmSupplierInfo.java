    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txtSupplierID.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Select a supplier first");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "Delete this supplier?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            String query = "delete from tblSupplierInfo where SuppID=?";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, txtSupplierID.getText());
            pst.execute();

            JOptionPane.showMessageDialog(null, "Deleted successfully");
            Reset();
            GenAutoID();
            Fill_Table();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased

        String val = txtSearch.getText();

        try {
            String qry = "select * from tblSupplierInfo where SuppName like ?";
            pst = (PreparedStatement) con.prepareStatement(qry);
            pst.setString(1, "%" + val + "%");
            rs = pst.executeQuery();

            DefaultTableModel model = (DefaultTableModel) tblBuyer.getModel();
            model.setRowCount(0);
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("SuppID"),
                    rs.getString("SuppName"),
                    rs.getString("Telephone")
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error at searchKeyReleased " + e);
        }
    }//GEN-LAST:event_txtSearchKeyReleased

    private void tblBuyerMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBuyerMouseClicked

        if (evt.getClickCount() == 2) {

            btnSave.setEnabled(false);
            btnUpdate.setEnabled(true);
            int row = tblBuyer.getSelectedRow();

            try {
                String Table_click = tblBuyer.getModel().getValueAt(row, 0).toString();
                String query = "SELECT * FROM tblSupplierInfo WHERE SuppID=?";
                pst = (PreparedStatement) con.prepareStatement(query);
                pst.setString(1, Table_click);
                rs = pst.executeQuery();
                if (rs.next()) {
                    txtSupplierID.setText(rs.getString("SuppID"));
                    txtSupplierName.setText(rs.getString("SuppName"));
                    txtAddress.setText(rs.getString("Address"));
                    txtBank.setText(rs.getString("Bank"));
                    txtTelephone.setText(rs.getString("Telephone"));
                    txtEmail.setText(rs.getString("Email"));
                    txtRemark.setText(rs.getString("Remarks"));
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_tblBuyerMouseClicked

    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(SuppID) AS MaxID FROM tblSupplierInfo");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtSupplierID.setText("SPI-00001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtSupplierID.setText("SPI-" + String.format("%05d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

    private void Fill_Table() {
        try {
            String query = "SELECT * FROM tblSupplierInfo";
            Statement st = con.createStatement();
            rs = st.executeQuery(query);

            DefaultTableModel model = (DefaultTableModel) tblBuyer.getModel();
            model.setRowCount(0);
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("SuppID"),
                    rs.getString("SuppName"),
                    rs.getString("Telephone")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

