    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

        int row = tblProductCategory.getSelectedRow();
        if (row > -1) {
            int opt = JOptionPane.showConfirmDialog(null, "Are You sure to Delete", "Delete", JOptionPane.YES_NO_OPTION);
            if (opt == 0) {
                try {

                    String value = tblProductCategory.getModel().getValueAt(row, 0).toString();
                    String query = "delete from tblproductcategory where prodCateId='" + value + "'";
                    pst = (PreparedStatement) con.prepareStatement(query);
                    pst.execute();
                    DefaultTableModel model = (DefaultTableModel) tblProductCategory.getModel();
                    model.setRowCount(0);

                //    fillTable();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(rootPane, e);
                }
            } else {
                DefaultTableModel model = (DefaultTableModel) tblProductCategory.getModel();
                model.setRowCount(0);
               // fillTable();
            }

        } else {

            JOptionPane.showMessageDialog(null, "Pls Selected Deleted Item");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

