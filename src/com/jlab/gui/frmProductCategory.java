    private void tblProductCategoryMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductCategoryMouseClicked

        if (evt.getClickCount() == 2) {
            btnUpdate.setEnabled(true);
            btnSave.setEnabled(false);
            int row = tblProductCategory.getSelectedRow();

            try {

                String Table_click = (tblProductCategory.getModel().getValueAt(row, 0).toString());
                String query = "SELECT * FROM tblproductcategory WHERE prodCateId='" + Table_click + "' ";
                pst = (PreparedStatement) con.prepareStatement(query);
                rs = pst.executeQuery();
                if (rs.next()) {

                    String add1 = rs.getString("prodCateId");
                    txtProdCateID.setText(add1);

                    String add2 = rs.getString("ProduCate");
                    txtProdCate.setText(add2);

                    String add3 = rs.getString("Descrip");
                    txtDescri.setText(add3);

                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }

        }


    }//GEN-LAST:event_tblProductCategoryMouseClicked

