    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(prodCateId) AS MaxID FROM tblproductcategory");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtProdCateID.setText("PC-00001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(3, rs.getString("MaxID").length()));
                id++;
                txtProdCateID.setText("PC-" + String.format("%05d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

