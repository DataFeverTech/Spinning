    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        if (tblExportLC.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Please add at least one Product row");
            return;
        }

        try {
            con.setAutoCommit(false);

            SaveGeneral();
            SaveProducts();

            con.commit();
            JOptionPane.showMessageDialog(this, "Registration Successfully Completed");
            Reset();

        } catch (Exception e) {
            try {
                con.rollback();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(null, ex);
            }
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                con.setAutoCommit(true);
            } catch (Exception ex) {
            }
        }

    }//GEN-LAST:event_btnSaveActionPerformed

    private void SaveGeneral() throws Exception {
        String lcType = rdoBLC.isSelected() ? rdoBLC.getText() : rdoAmnd.getText();
        String lcCategory = rdoLocal.isSelected() ? rdoLocal.getText()
                : rdoForeign.isSelected() ? rdoForeign.getText() : "";
        String lcDate = ((JTextField) dtImport.getDateEditor().getUiComponent()).getText();
        String shipmentDate = ((JTextField) dtShipment.getDateEditor().getUiComponent()).getText();
        String validityDate = ((JTextField) dtValidity.getDateEditor().getUiComponent()).getText();
        String piDate = ((JTextField) dtPI.getDateEditor().getUiComponent()).getText();
        String query = "Insert into tblImportLCFixedAssets(ImportID,SubFile,LCType,ImportLCNo,LCDate,LCCategory,"
                + "SupplierName,Shipment,Validity,LCValue,Rate,PINo,PIDate,Remarks) "
                + "values (?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        pst = (PreparedStatement) con.prepareStatement(query);
        pst.setString(1, txtImportID.getText());
        pst.setString(2, txtFileNo.getText());
        pst.setString(3, lcType);
        pst.setString(4, (String) cboImportLC.getSelectedItem());
        pst.setString(5, lcDate);
        pst.setString(6, lcCategory);
        pst.setString(7, (String) cboSupplierName.getSelectedItem());
        pst.setString(8, shipmentDate);
        pst.setString(9, validityDate);
        pst.setDouble(10, Double.parseDouble(txtLCValue.getText()));
        pst.setDouble(11, Double.parseDouble(txtRate.getText()));
        pst.setString(12, txtPINo.getText());
        pst.setString(13, piDate);
        pst.setString(14, txtRemarks.getText());
        pst.execute();
    }

    private void SaveProducts() throws Exception {
        String query = "Insert into tblImportLCFixedAssetsProducts(ImportID,Product,Ref,Qty,Unit,UnitPrice,TotalValue) "
                + "values (?,?,?,?,?,?,?)";
        pst = (PreparedStatement) con.prepareStatement(query);

        DefaultTableModel model = (DefaultTableModel) tblExportLC.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            pst.setString(1, txtImportID.getText());
            pst.setString(2, model.getValueAt(i, 0).toString());
            pst.setString(3, model.getValueAt(i, 1).toString());
            pst.setDouble(4, Double.parseDouble(model.getValueAt(i, 2).toString()));
            pst.setString(5, model.getValueAt(i, 3).toString());
            pst.setDouble(6, Double.parseDouble(model.getValueAt(i, 4).toString()));
            pst.setDouble(7, Double.parseDouble(model.getValueAt(i, 5).toString()));
            pst.addBatch();
        }
        pst.executeBatch();
    }
