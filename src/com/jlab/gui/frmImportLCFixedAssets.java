    private void cboImportLCActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboImportLCActionPerformed
        String selected = (String) cboImportLC.getSelectedItem();
        if (selected == null || selected.equals(".")) {
            return;
        }
        try {
            String query = "SELECT * FROM tblImportLC WHERE ImportLCNo=?";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, selected);
            rs = pst.executeQuery();
            if (rs.next()) {
                cboSupplierName.setSelectedItem(rs.getString("SupplierName"));
                txtPINo.setText(rs.getString("PINo"));
                txtLCValue.setText(rs.getString("LCValue"));

                String piDateStr = rs.getString("PIDate");
                if (piDateStr != null && !piDateStr.isEmpty()) {
                    try {
                        Date piDate = new SimpleDateFormat("dd-MM-yyyy").parse(piDateStr);
                        dtPI.setDate(piDate);
                    } catch (ParseException ex) {
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboImportLCActionPerformed

    private void calculateTotal() {
        try {
            double qty = Double.parseDouble(txtQty.getText().trim());
            double unitPrice = Double.parseDouble(txtUnitPrice.getText().trim());
            txtTotalValue.setText(String.valueOf(qty * unitPrice));
        } catch (NumberFormatException e) {
            txtTotalValue.setText("");
        }
    }

