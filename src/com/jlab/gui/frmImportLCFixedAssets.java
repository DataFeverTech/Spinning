    private String getTableName(String selected) {
        if (selected == null) {
            return null;
        }
        switch (selected) {
            case "Ready Garments":
                return "tblReadyGarments";
            case "Fabrics":
                return "tblFabrics";
            case "WashPrint Embroidery":
                return "tblWashPrintEmbroidery";
            case "Accessories":
                return "tblAccessories";
            case "Packing Material":
                return "tblPackingMaterial";
            case "Loose Tools Fixed Assets":
                return "tblKnittingCharge";
            default:
                return null;
        }
    }

