    private void tblYarnCountMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblYarnCountMouseClicked
        int r = tblYarnCount.getSelectedRow();
        if (r < 0) {
            return;
        }
        txtYarnId.setText(tblYarnCount.getValueAt(r, 0).toString());
        txtYarnCount.setText(tblYarnCount.getValueAt(r, 1).toString());
        try {
            pst = con.prepareStatement("select Remarks from tblYarnCount where YarnID=?");
            pst.setString(1, txtYarnId.getText());
            ResultSet r2 = pst.executeQuery();
            txtRemarks.setText(r2.next() && r2.getString(1) != null ? r2.getString(1) : "");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_tblYarnCountMouseClicked

    private boolean isDuplicate(String name, String id) {
        try {
            pst = con.prepareStatement("select count(*) from tblYarnCount where YarnCount=? and YarnID<>?");
            pst.setString(1, name);
            pst.setString(2, id);
            ResultSet r = pst.executeQuery();
            r.next();
            return r.getInt(1) > 0;
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
            return true;
        }
    }

    public void fillTable() {
        DefaultTableModel model = (DefaultTableModel) tblYarnCount.getModel();
        model.setRowCount(0);
        try {
            pst = con.prepareStatement("select YarnID, YarnCount from tblYarnCount where YarnCount like ? order by YarnID");
            pst.setString(1, "%" + txtSearch.getText().trim() + "%");
            ResultSet r = pst.executeQuery();
            while (r.next()) {
                model.addRow(new Object[]{r.getString("YarnID"), r.getString("YarnCount")});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(YarnID) AS MaxID FROM tblYarnCount");
            r.next();
            String max = r.getString("MaxID");
            if (max == null) {
                txtYarnId.setText("YC-00001");
            } else {
                long id = Long.parseLong(max.substring(3));
                id++;
                txtYarnId.setText("YC-" + String.format("%05d", id));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

