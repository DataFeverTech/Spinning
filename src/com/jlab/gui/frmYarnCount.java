    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (tblYarnCount.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "Please select a row from the table.");
            return;
        }
        if (txtYarnCount.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Yarn Count.");
            return;
        }
        if (isDuplicate(txtYarnCount.getText().trim(), txtYarnId.getText())) {
            JOptionPane.showMessageDialog(this, "This Yarn Count already exists.");
            return;
        }
        try {
            String query = "update tblYarnCount set YarnCount=?, Remarks=? where YarnID=?";
            pst = con.prepareStatement(query);
            pst.setString(1, txtYarnCount.getText().trim());
            pst.setString(2, txtRemarks.getText().trim());
            pst.setString(3, txtYarnId.getText());
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Updated successfully.");
            Reset();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

