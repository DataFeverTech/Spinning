    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        if (txtYarnCount.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Yarn Count.");
            txtYarnCount.requestFocus();
            return;
        }
        if (isDuplicate(txtYarnCount.getText().trim(), txtYarnId.getText())) {
            JOptionPane.showMessageDialog(this, "This Yarn Count already exists.");
            return;
        }
        try {
            String query = "insert into tblYarnCount(YarnID,YarnCount,Remarks) values (?,?,?)";
            pst = con.prepareStatement(query);
            pst.setString(1, txtYarnId.getText());
            pst.setString(2, txtYarnCount.getText().trim());
            pst.setString(3, txtRemarks.getText().trim());
            pst.execute();
            JOptionPane.showMessageDialog(this, "Saved successfully.");
            Reset();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }

    }//GEN-LAST:event_btnSaveActionPerformed

