    public ArrayList<ReadyGarHead_Bean> getAllData() {
        ArrayList<ReadyGarHead_Bean> al = null;
        al = new ArrayList<ReadyGarHead_Bean>();
        try {

            String qry = "select * from tblPackingHead";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            ReadyGarHead_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new ReadyGarHead_Bean(rs.getString("HeadId"),
                        rs.getString("HeadName"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void fillTable() {
        ArrayList<ReadyGarHead_Bean> al = getAllData();
        DefaultTableModel model = (DefaultTableModel) tblunit.getModel();
        //  tblChequeDetails.getColumnModel().getColumn(0).setPreferredWidth(10);
        model.setRowCount(0); // Empty/clear the table
        Object[] row = new Object[2];
        for (int i = 0; i < al.size(); i++) {
            row[0] = al.get(i).getHeadId();
            row[1] = al.get(i).getName();
            model.addRow(row);

        }
    }

    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(HeadId) AS MaxID FROM tblPackingHead");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtHeadID.setText("PCH-0001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtHeadID.setText("PCH-" + String.format("%04d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

