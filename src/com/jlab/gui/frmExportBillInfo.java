    private void Fill_CommercialInvoice(String exportLC) {
        cboInvoiceNo.removeAllItems();
        try {
            String query = "SELECT * FROM tblCommercialInvoice WHERE ExportLC=?";
            PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, exportLC);
            rs = pst.executeQuery();
            while (rs.next()) {
                String cname = rs.getString("InvoiceNo");
                cboInvoiceNo.addItem(cname);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
            con.setAutoCommit(false);

            SubmitCommercialInv();
            SubmitCommercialInvProduct();

            con.commit();
            JOptionPane.showMessageDialog(this, "Saved Successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception e) {
            try {
                con.rollback();
                JOptionPane.showMessageDialog(this, "Save Failed! Rolled back.\n" + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage());
            }
        } finally {
            try {
                con.setAutoCommit(true);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    public void SubmitCommercialInv() throws Exception {

        int pur = 1;
        int coll = 1;

        date = dtBillDate.getDate();
        Billdate = new java.sql.Date(date.getTime());

        String date1 = ((JTextField) dtMaturity.getDateEditor().getUiComponent()).getText();

        String query = "Insert into tblExportBill(ExportBillNo,ExportDate,ExportLC,Rate,Purchase,Collection,MaturityDate,TotalValue,TotalAmount,Remarks) values (?,?,?,?,?,?,?,?,?,?)";
        try {

            PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);

            pst.setString(1, txtExportBillNo.getText());
            pst.setDate(2, Billdate);
            pst.setString(3, cboExportLC.getSelectedItem().toString());
            pst.setString(4, txtRate.getText());
            if (rdoPurchase.isSelected() == true) {
                pur = 0;
            } else {
                pur = 1;
            }
            if (rdoCollection.isSelected() == true) {
                coll = 0;
            } else {
                coll = 1;
            }
            pst.setInt(5, pur);
            pst.setInt(6, coll);
            pst.setString(7, date1);
            pst.setString(8, txtTotalTableValue.getText());
            pst.setString(9, txtTotalTableAmount.getText());
            pst.setString(10, txtRemarks.getText());
            pst.executeUpdate();

            //JOptionPane.showMessageDialog(null, "Saved!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }

    }

    public void SubmitCommercialInvProduct() throws Exception {

        try {

            int rows = tblExportBill.getRowCount();
            //       con.setAutoCommit(false);
            String query = "Insert into tblExportBillProduct(ExportBillNo,InvoiceNo,Quantity,Unit,Price,Value,TotalVal) values (?,?,?,?,?,?,?)";
            PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
            for (int row = 0; row < rows; row++) {

                String InvoiceNo = (String) tblExportBill.getValueAt(row, 0);
                String Quantity = (String) tblExportBill.getValueAt(row, 1);
                String Unit = (String) tblExportBill.getValueAt(row, 2);
                String Price = (String) tblExportBill.getValueAt(row, 3);
                String Value = (String) tblExportBill.getValueAt(row, 4);
                String TotalValue = (String) tblExportBill.getValueAt(row, 5);

                pst.setString(1, txtExportBillNo.getText());
                pst.setString(2, InvoiceNo);
                pst.setString(3, Quantity);
                pst.setString(4, Unit);
                pst.setString(5, Price);
                pst.setString(6, Value);
                pst.setString(7, TotalValue);

                pst.addBatch();

            }

            pst.executeBatch();
            //     con.commit();
            //JOptionPane.showMessageDialog(null, "Saved!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }

    }


