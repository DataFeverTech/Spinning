    public ArrayList<Unit_Bean> getAllData() {
        ArrayList<Unit_Bean> al = null;
        al = new ArrayList<Unit_Bean>();
        try {

            String qry = "select * from tblunitmeas";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            Unit_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new Unit_Bean(rs.getString("unitId"),
                        rs.getString("Unit"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(BillNo) AS MaxID FROM tblImportBillInfo");
            rs.next();
            if (rs.getString("MaxID") == null) {
                txtBillNo.setText("MS-00001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(3, rs.getString("MaxID").length()));
                id++;
                txtBillNo.setText("MS-" + String.format("%05d", id));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

