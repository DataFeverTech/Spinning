    private void cboInvoiceNoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboInvoiceNoActionPerformed
        String selected = (String) cboInvoiceNo.getSelectedItem();
        if (selected == null || selected.equals("Select Invoice")) {
            return;
        }
        try {
            String query = "SELECT * FROM tblImportInfo WHERE ImportInfoID=?";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, selected);
            rs = pst.executeQuery();
            if (rs.next()) {
                txtExportLC.setText(rs.getString("ExportLC"));
                txtImportLC.setText(rs.getString("ImportLC"));
                txtInvoiceValue.setText(rs.getString("InvoiceValue"));

                String purchaseDateStr = rs.getString("PurchaseDate");
                if (purchaseDateStr != null && !purchaseDateStr.isEmpty()) {
                    try {
                        Date purchaseDate = new SimpleDateFormat("dd-MM-yyyy").parse(purchaseDateStr);
                        dtMaturityDate.setDate(purchaseDate);
                    } catch (ParseException ex) {
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboInvoiceNoActionPerformed

