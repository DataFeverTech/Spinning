    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        String selectedInvoice = (String) cboInvoiceNo.getSelectedItem();
        if (selectedInvoice == null || selectedInvoice.equals("Select Invoice")) {
            JOptionPane.showMessageDialog(this, "Please select an Invoice No");
            return;
        }

        try {
            String billDate = ((javax.swing.JTextField) dtExport.getDateEditor().getUiComponent()).getText();
            String maturityDate = ((javax.swing.JTextField) dtMaturityDate.getDateEditor().getUiComponent()).getText();

            String query = "Insert into tblImportBillInfo(BillNo,BillDate,Rate,Currency,InvoiceNo,ExportLC,ImportLC,InvoiceValue,MaturityDate,Remarks) "
                    + "values (?,?,?,?,?,?,?,?,?,?)";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, txtBillNo.getText());
            pst.setString(2, billDate);
            pst.setDouble(3, Double.parseDouble(txtRate.getText()));
            pst.setString(4, (String) cboCurrency.getSelectedItem());
            pst.setString(5, selectedInvoice);
            pst.setString(6, txtExportLC.getText());
            pst.setString(7, txtImportLC.getText());
            pst.setString(8, txtInvoiceValue.getText());
            pst.setString(9, maturityDate);
            pst.setString(10, txtRemarks.getText());
            pst.execute();

            JOptionPane.showMessageDialog(this, "Registration Successfully Completed");
            Reset();
            GenAutoID();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Rate/Invoice Value must be numeric");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

