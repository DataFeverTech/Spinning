    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (tblMachine.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "Please select a row from the table.");
            return;
        }
        if (txtMachineName.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Machine Name.");
            return;
        }
        if (isDuplicate(txtMachineName.getText().trim(), txtMachineId.getText())) {
            JOptionPane.showMessageDialog(this, "This Machine Name already exists.");
            return;
        }
        try {
            String query = "update tblMachine set MachineName=?, Remarks=? where MachineID=?";
            pst = con.prepareStatement(query);
            pst.setString(1, txtMachineName.getText().trim());
            pst.setString(2, txtRemarks.getText().trim());
            pst.setString(3, txtMachineId.getText());
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Updated successfully.");
            Reset();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

