    private void tblMachineMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMachineMouseClicked
        int r = tblMachine.getSelectedRow();
        if (r < 0) {
            return;
        }
        txtMachineId.setText(tblMachine.getValueAt(r, 0).toString());
        txtMachineName.setText(tblMachine.getValueAt(r, 1).toString());
        try {
            pst = con.prepareStatement("select Remarks from tblMachine where MachineID=?");
            pst.setString(1, txtMachineId.getText());
            ResultSet r2 = pst.executeQuery();
            txtRemarks.setText(r2.next() && r2.getString(1) != null ? r2.getString(1) : "");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_tblMachineMouseClicked

    private boolean isDuplicate(String name, String id) {
        try {
            pst = con.prepareStatement("select count(*) from tblMachine where MachineName=? and MachineID<>?");
            pst.setString(1, name);
            pst.setString(2, id);
            ResultSet r = pst.executeQuery();
            r.next();
            return r.getInt(1) > 0;
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
            return true;
        }
    }

    public void fillTable() {
        DefaultTableModel model = (DefaultTableModel) tblMachine.getModel();
        model.setRowCount(0);
        try {
            pst = con.prepareStatement("select MachineID, MachineName from tblMachine where MachineName like ? order by MachineID");
            pst.setString(1, "%" + txtSearch.getText().trim() + "%");
            ResultSet r = pst.executeQuery();
            while (r.next()) {
                model.addRow(new Object[]{r.getString("MachineID"), r.getString("MachineName")});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(MachineID) AS MaxID FROM tblMachine");
            r.next();
            String max = r.getString("MaxID");
            if (max == null) {
                txtMachineId.setText("MC-00001");
            } else {
                long id = Long.parseLong(max.substring(3));
                id++;
                txtMachineId.setText("MC-" + String.format("%05d", id));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

