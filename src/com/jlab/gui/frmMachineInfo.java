    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        if (txtMachineName.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Machine Name.");
            txtMachineName.requestFocus();
            return;
        }
        if (isDuplicate(txtMachineName.getText().trim(), txtMachineId.getText())) {
            JOptionPane.showMessageDialog(this, "This Machine Name already exists.");
            return;
        }
        try {
            String query = "insert into tblMachine(MachineID,MachineName,Remarks) values (?,?,?)";
            pst = con.prepareStatement(query);
            pst.setString(1, txtMachineId.getText());
            pst.setString(2, txtMachineName.getText().trim());
            pst.setString(3, txtRemarks.getText().trim());
            pst.execute();
            JOptionPane.showMessageDialog(this, "Saved successfully.");
            Reset();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }

    }//GEN-LAST:event_btnSaveActionPerformed

