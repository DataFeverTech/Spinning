    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        try {
            con.setAutoCommit(false);

            SubmitCommercialInv();
            SubmitCommercialInvProduct();

            con.commit();
            JOptionPane.showMessageDialog(this, "Commercial Invoice Saved Successfully");
            Reset();
        } catch (Exception e) {
            try {
                con.rollback();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Rollback Failed: " + ex.getMessage());
            }
            JOptionPane.showMessageDialog(this, "Save Failed: " + e.getMessage());
        } finally {
            try {
                con.setAutoCommit(true);
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage());
            }
        }

    }//GEN-LAST:event_btnSaveActionPerformed

    public void SubmitCommercialInv() throws Exception {

        int fob = 1;
        int cnf = 1;
        int Sea = 1;
        int Air = 1;
        int Loc = 1;

        date = dtInvoiceDate.getDate();
        Invdate = new java.sql.Date(date.getTime());

        String date1 = ((JTextField) dtExpNoDate.getDateEditor().getUiComponent()).getText();
        String date2 = ((JTextField) dtBillDate.getDateEditor().getUiComponent()).getText();
        String query = "Insert into tblCommercialInvoice(InvoiceNo,InvDate,ExportNo,ExportDate,Rate,Sea,Air,Loc,ExportLC,BillNo,BillDate,Quantity,Unit,TotalValue,Fob,Cnf,Flight,Discount) values (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";

        PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);

        pst.setString(1, txtInvoiceNo.getText());
        pst.setDate(2, Invdate);
        pst.setString(3, txtExportNo.getText());
        pst.setString(4, date1);
        pst.setString(5, txtRate.getText());
        if (rdoSea.isSelected() == true) {
            Sea = 0;
        } else {
            Sea = 1;
        }
        if (rdoAir.isSelected() == true) {
            Air = 0;
        } else {
            Air = 1;
        }
        if (rdoLoc.isSelected() == true) {
            Loc = 0;
        } else {
            Loc = 1;
        }
        pst.setInt(6, Sea);
        pst.setInt(7, Air);
        pst.setInt(8, Loc);
        pst.setString(9, cboExportLC.getSelectedItem().toString());
        pst.setString(10, txtBillNO.getText());
        pst.setString(11, date2);
        pst.setString(12, txtQuantity.getText());
        pst.setString(13, cboUnit.getSelectedItem().toString());
        pst.setString(14, txtValue.getText());
        if (rdoFob.isSelected() == true) {
            fob = 0;
        } else {
            fob = 1;
        }
        if (rdoCnf.isSelected() == true) {
            cnf = 0;
        } else {
            cnf = 1;
        }
        pst.setInt(15, fob);
        pst.setInt(16, cnf);
        pst.setString(17, txtFlight.getText());
        pst.setString(18, txtDiscount.getText());
        pst.executeUpdate();
    }

    public void SubmitCommercialInvProduct() throws Exception {

        int rows = tblExportLC.getRowCount();
        String query = "Insert into tblCommercialInvProduct(InvoiceNo,JobOrder,Garments,Shipment,Quantity,Unit,Price,TotalValue,BFCom,BICom) values (?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
        for (int row = 0; row < rows; row++) {

            String JobOrder = (String) tblExportLC.getValueAt(row, 0);
            String Garments = (String) tblExportLC.getValueAt(row, 1);
            String Shipment = (String) tblExportLC.getValueAt(row, 2);
            String Quantity = (String) tblExportLC.getValueAt(row, 3);
            String Unit = (String) tblExportLC.getValueAt(row, 4);
            String Price = (String) tblExportLC.getValueAt(row, 5);
            String TotalValue = (String) tblExportLC.getValueAt(row, 6);
            String BFCom = (String) tblExportLC.getValueAt(row, 7);
            String BICom = (String) tblExportLC.getValueAt(row, 8);

            pst.setString(1, txtInvoiceNo.getText());
            pst.setString(2, JobOrder);
            pst.setString(3, Garments);
            pst.setString(4, Shipment);
            pst.setString(5, Quantity);
            pst.setString(6, Unit);
            pst.setString(7, Price);
            pst.setString(8, TotalValue);
            pst.setString(9, BFCom);
            pst.setString(10, BICom);

            pst.addBatch();
        }
        pst.executeBatch();
    }


