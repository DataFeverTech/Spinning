    public void GenAutoID() {

        try {
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(InvoiceNo) AS MaxID FROM tblCommercialInvoice");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtInvoiceNo.setText("CMI-0000001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtInvoiceNo.setText("CMI-" + String.format("%07d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

