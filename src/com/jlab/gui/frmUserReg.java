    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased

        ArrayList<User_Bean> al = null;
        al = new ArrayList<User_Bean>();
        String val = txtSearch.getText().toString();

        try {

            String qry = "select * from tblUserInfo where UserName like '%" + val + "%'";
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery(qry);
            User_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new User_Bean(rs.getString("UserID"),
                        rs.getString("UserName"), rs.getString("Des"));
                al.add(LoadTable);
            }

            //search ed teachers to be added to datatable
            DefaultTableModel model = (DefaultTableModel) tblUser.getModel();
            model.setRowCount(0); // Empty/clear the table
            Object[] row = new Object[3];
            for (int i = 0; i < al.size(); i++) {
                row[0] = al.get(i).getUserid();
                row[1] = al.get(i).getUser();
                row[2] = al.get(i).getDescri();

                model.addRow(row);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error at searchKeyReleased " + e);
        }

    }//GEN-LAST:event_txtSearchKeyReleased

