    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        int che = 1;
        int mai = 1;
        int trs = 1;
        int rep = 1;

        String password = new String(txtPassword.getPassword());
        String confpassword = new String(txtConfPass.getPassword());

        if (password.equals(confpassword)) {

            try {
                String query = "insert into tblUserInfo(UserID,Username,Password,Des,chkBasic,chkMain,chkTran,chkReport) values (?,?,?,?,?,?,?,?)";
                pst = (PreparedStatement) con.prepareStatement(query);

                pst.setString(1, txtUserID.getText());
                pst.setString(2, txtUsername.getText());
                pst.setString(3, txtPassword.getText());
                pst.setString(4, txtDes.getText());

                if (chkBasic.isSelected() == true) {
                    che = 0;
                } else {
                    che = 1;
                }
                if (chkMaintenace.isSelected() == true) {
                    mai = 0;
                } else {
                    mai = 1;
                }
                if (chkImport.isSelected() == true) {
                    trs = 0;
                } else {
                    trs = 1;
                }
                if (chkReport.isSelected() == true) {
                    rep = 0;
                } else {
                    rep = 1;
                }

                pst.setInt(5, che);
                pst.setInt(6, mai);
                pst.setInt(7, trs);
                pst.setInt(8, rep);

                pst.execute();

                JOptionPane.showMessageDialog(this, "User Registration SuccusFully Compled");
                Reset();
                fillTable();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Check Your UserName OR Password ");
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDelete2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDelete2ActionPerformed

        int row = tblUser.getSelectedRow();
        if (row > -1) {
            int opt = JOptionPane.showConfirmDialog(null, "Are You sure to Delete", "Delete", JOptionPane.YES_NO_OPTION);
            if (opt == 0) {
                try {

                    String value = tblUser.getModel().getValueAt(row, 0).toString();
                    String query = "delete from tblUserInfo where userid=?";
                    pst = (PreparedStatement) con.prepareStatement(query);
                    pst.setString(1, value);
                    pst.execute();
                    DefaultTableModel model = (DefaultTableModel) tblUser.getModel();
                    model.setRowCount(0);
                    Reset();
                    fillTable();
                    GenAutoID();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(rootPane, e);
                }
            } else {
                DefaultTableModel model = (DefaultTableModel) tblUser.getModel();
                model.setRowCount(0);
                fillTable();
            }
        } else {

            JOptionPane.showMessageDialog(null, "Pls Selected Deleted Item");
        }
    }//GEN-LAST:event_btnDelete2ActionPerformed

