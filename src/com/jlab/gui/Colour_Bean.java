package com.jlab.gui;

/**
 *
 * @author Jewel
 */
public class Colour_Bean {
    
    private String Id;
    private String name;

    public Colour_Bean() {
    }

    public Colour_Bean(String Id, String name) {
        this.Id = Id;
        this.name = name;
    }

    public String getId() {
        return Id;
    }

    public void setId(String Id) {
        this.Id = Id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
  

  
    
    
}
