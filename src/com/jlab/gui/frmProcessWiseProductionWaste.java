    // ---------- Helpers ----------
    private double num(String s) {
        try {
            return Double.parseDouble(s.trim());
        } catch (Exception e) {
            return 0;
        }
    }

    private java.sql.Date sqlDate(com.toedter.calendar.JDateChooser dc) {
        return dc.getDate() == null ? null : new java.sql.Date(dc.getDate().getTime());
    }

    private String sel(javax.swing.JComboBox<String> c) {
        Object o = c.getSelectedItem();
        return o == null ? "" : o.toString();
    }

    private boolean notSel(javax.swing.JComboBox<String> c) {
        String s = sel(c);
        return s.equals("") || s.equals("Select Product Info");
    }

// ---------- Fill Combo ----------
    private void FillCombo(javax.swing.JComboBox<String> cbo, String query, String col) {
        try {
            cbo.removeAllItems();
            cbo.addItem("Select Product Info");
            PreparedStatement p = con.prepareStatement(query);
            ResultSet r = p.executeQuery();
            while (r.next()) {
                cbo.addItem(r.getString(col));
            }
            r.close();
            p.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

