    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblProcessWasteGeneral "
                + "(EntryNo, EntryDate, WorkOrder, Party, Shift, YarnCount, EndUse, Target, IssueNo, CottonIssued, Remarks, "
                + "TotalCottonIn, TotalYarnOut, TotalWaste, TotalYield) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtEntryNo.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, sel(cboWorkOrder));
        p.setString(4, txtParty.getText());
        p.setString(5, sel(cboShift));
        p.setString(6, sel(cboYarnCount1));
        p.setString(7, sel(cboEndUse));
        p.setString(8, txtTarget.getText());
        p.setString(9, sel(cboIssueNO));
        p.setString(10, txtCottonIssued.getText());
        p.setString(11, txtRemarks.getText());
        p.setString(12, txtTotalCottonIn.getText());
        p.setString(13, txtTotaYarnOut.getText());
        p.setString(14, txtTotalYarn1.getText());
        p.setString(15, txtTotalDays1.getText());
        p.executeUpdate();
        p.close();
    }

    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblProcessWasteDetail "
                + "(EntryNo, SL, Process, Machine, Operator, Speed, Unit, InputKg, OutputKg, WasteKg, WastePer, StdPer, Status) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblProcessWiseProductionWaste.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtEntryNo.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            p.setString(3, model.getValueAt(i, 1).toString());
            p.setString(4, model.getValueAt(i, 2).toString());
            p.setString(5, model.getValueAt(i, 11).toString());
            p.setString(6, model.getValueAt(i, 3).toString());
            p.setString(7, model.getValueAt(i, 4).toString());
            p.setString(8, model.getValueAt(i, 5).toString());
            p.setString(9, model.getValueAt(i, 6).toString());
            p.setString(10, model.getValueAt(i, 7).toString());
            p.setString(11, model.getValueAt(i, 8).toString());
            p.setString(12, model.getValueAt(i, 9).toString());
            p.setString(13, model.getValueAt(i, 10).toString());
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }
