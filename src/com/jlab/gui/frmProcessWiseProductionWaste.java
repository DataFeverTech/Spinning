// ---------- ID ----------
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(EntryNo) AS MaxID FROM tblProcessWasteGeneral");
            r.next();
            if (r.getString("MaxID") == null) {
                txtEntryNo.setText("PWP-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(4));
                id++;
                txtEntryNo.setText("PWP-" + String.format("%07d", id));
            }
            txtEntryNo.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

