// ---------- Auto Calc (Waste, Waste %) ----------
    private void CalcWaste() {
        double in = num(txtInput.getText());
        double out = num(txtOutput.getText());
        double waste = in - out;
        txtWaste.setText(String.format("%.2f", waste));
        txtWasteInPer.setText(in == 0 ? "0.00" : String.format("%.2f", (waste / in) * 100));
    }

    // ---------- Grid Add ----------
    public void GridAdd() {
        if (notSel(cboProcess)) {
            JOptionPane.showMessageDialog(this, "Select Process");
            return;
        }
        if (notSel(cboMachine)) {
            JOptionPane.showMessageDialog(this, "Select Machine");
            return;
        }
        if (txtInput.getText().trim().isEmpty() || txtOutput.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Input & Output");
            return;
        }

        String status = num(txtWasteInPer.getText()) > num(txtStdWaste.getText()) ? "High" : "OK";
        String operator = notSel(cboOperator) ? "" : sel(cboOperator);

        DefaultTableModel model = (DefaultTableModel) tblProcessWiseProductionWaste.getModel();
        model.addRow(new Object[]{
            model.getRowCount() + 1,
            sel(cboProcess),
            sel(cboMachine),
            txtSpeed.getText(),
            sel(cboSpeedUnit),
            txtInput.getText(),
            txtOutput.getText(),
            txtWaste.getText(),
            txtWasteInPer.getText(),
            txtStdWaste.getText(),
            status,
            operator
        });

        CalcTotal();
        ClearProductFields();
    }

    private void ClearProductFields() {
        cboProcess.setSelectedIndex(0);
        cboMachine.setSelectedIndex(0);
        cboOperator.setSelectedIndex(0);
        txtSpeed.setText("");
        txtStdWaste.setText("");
        txtInput.setText("");
        txtOutput.setText("");
        txtWaste.setText("");
        txtWasteInPer.setText("");
    }

    private void CalcTotal() {
        DefaultTableModel model = (DefaultTableModel) tblProcessWiseProductionWaste.getModel();
        double in = 0, out = 0, waste = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            in += num(String.valueOf(model.getValueAt(i, 5)));
            out += num(String.valueOf(model.getValueAt(i, 6)));
            waste += num(String.valueOf(model.getValueAt(i, 7)));
        }
        txtTotalCottonIn.setText(String.format("%.2f", in));
        txtTotaYarnOut.setText(String.format("%.2f", out));
        txtTotalYarn1.setText(String.format("%.2f", waste));
        txtTotalDays1.setText(in == 0 ? "0.00" : String.format("%.2f", (out / in) * 100));  // Yield %
    }

    // ---------- Reset ----------
    private void Reset() {
        cboWorkOrder.setSelectedIndex(0);
        cboShift.setSelectedIndex(0);
        cboYarnCount1.setSelectedIndex(0);
        cboEndUse.setSelectedIndex(0);
        cboIssueNO.setSelectedIndex(0);
        txtParty.setText("");
        txtTarget.setText("");
        txtCottonIssued.setText("");
        txtRemarks.setText("");
        txtTotalCottonIn.setText("");
        txtTotaYarnOut.setText("");
        txtTotalYarn1.setText("");
        txtTotalDays1.setText("");
        ClearProductFields();
        ((DefaultTableModel) tblProcessWiseProductionWaste.getModel()).setRowCount(0);
        GenAutoID();
        ShowLocal();
    }


