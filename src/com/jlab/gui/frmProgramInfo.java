    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(ProgramID) AS MaxID FROM tblProgramInfo");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtProgramID.setText("PGM-00001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtProgramID.setText("PGM-" + String.format("%05d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

