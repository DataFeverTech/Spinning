    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

        int row = tblYarnType.getSelectedRow();
        if (row > -1) {
            int opt = JOptionPane.showConfirmDialog(null, "Are You sure to Delete", "Delete", JOptionPane.YES_NO_OPTION);
            if (opt == 0) {
                try {
                    String value = tblYarnType.getModel().getValueAt(row, 0).toString();
                    String query = "DELETE FROM tblYarnType WHERE YarnTypeId=?";
                    pst = (PreparedStatement) con.prepareStatement(query);
                    pst.setString(1, value);
                    pst.execute();
                    JOptionPane.showMessageDialog(null, "Deleted Successfully!");
                    DefaultTableModel model = (DefaultTableModel) tblYarnType.getModel();
                    model.setRowCount(0);
                    Reset();
                    fillTable();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(rootPane, e);
                }
            } else {
                DefaultTableModel model = (DefaultTableModel) tblYarnType.getModel();
                model.setRowCount(0);
                fillTable();
            }
        } else {
            JOptionPane.showMessageDialog(null, "Please Select an Item to Delete");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased

        String val = txtSearch.getText().toString();
        try {
            String qry = "SELECT * FROM tblYarnType WHERE YarnTypeName LIKE ?";
            pst = (PreparedStatement) con.prepareStatement(qry);
            pst.setString(1, "%" + val + "%");
            ResultSet rs = pst.executeQuery();

            DefaultTableModel model = (DefaultTableModel) tblYarnType.getModel();
            model.setRowCount(0);

            while (rs.next()) {
                Object[] row = new Object[2];
                row[0] = rs.getString("YarnTypeId");
                row[1] = rs.getString("YarnTypeName");
                model.addRow(row);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error at searchKeyReleased " + e);
        }


    }//GEN-LAST:event_txtSearchKeyReleased

    private void tblYarnTypeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblYarnTypeMouseClicked

        if (evt.getClickCount() == 2) {
            btnSave.setEnabled(false);
            btnUpdate.setEnabled(true);
            int row = tblYarnType.getSelectedRow();
            try {
                String Table_click = tblYarnType.getModel().getValueAt(row, 0).toString();
                String query = "SELECT * FROM tblYarnType WHERE YarnTypeId=?";
                pst = (PreparedStatement) con.prepareStatement(query);
                pst.setString(1, Table_click);
                rs = pst.executeQuery();
                if (rs.next()) {
                    txtComposID.setText(rs.getString("YarnTypeId"));
                    txtComposName.setText(rs.getString("YarnTypeName"));
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }

    }//GEN-LAST:event_tblYarnTypeMouseClicked

