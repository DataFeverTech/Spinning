    //show / add the the data to table
    public ArrayList<Unit_Bean> getAllData() {
        ArrayList<Unit_Bean> al = null;
        al = new ArrayList<Unit_Bean>();
        try {

            String qry = "select * from tblYarnType";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            Unit_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new Unit_Bean(rs.getString("YarnTypeID"), rs.getString("YarnTypeName"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void fillTable() {
        ArrayList<Unit_Bean> al = getAllData();
        DefaultTableModel model = (DefaultTableModel) tblYarnType.getModel();
        //  tblChequeDetails.getColumnModel().getColumn(0).setPreferredWidth(10);
        model.setRowCount(0); // Empty/clear the table
        Object[] row = new Object[3];
        for (int i = 0; i < al.size(); i++) {
            row[0] = al.get(i).getUnitId();
            row[1] = al.get(i).getUnit();
            model.addRow(row);

        }
    }

    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(YarnTypeId) AS MaxID FROM tblYarnType");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtComposID.setText("YT-0001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(3, rs.getString("MaxID").length()));
                id++;
                txtComposID.setText("YT-" + String.format("%04d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

