    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(ReqId) AS MaxID FROM tblCottonRequisition");
            r.next();
            if (r.getString("MaxID") == null) {
                txtReqId.setText("CRQ-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(4));
                id++;
                txtReqId.setText("CRQ-" + String.format("%07d", id));
            }
            txtReqId.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

