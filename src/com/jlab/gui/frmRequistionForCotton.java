    private void cboWorkOrderPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboWorkOrderPopupMenuWillBecomeInvisible
        txtBuyer.setText("");
        txtYarnCount.setText("");
        txtYarnQty.setText("");
        txtAlreadyReq.setText("");
        txtBalance.setText("");
        if (notSel(cboWorkOrder)) {
            return;
        }
        try {
            PreparedStatement p = con.prepareStatement("SELECT Party FROM tblWorkOrder WHERE WorkOrderNo=?");
            p.setString(1, sel(cboWorkOrder));
            ResultSet r = p.executeQuery();
            if (r.next()) {
                txtBuyer.setText(r.getString("Party"));
            }
            r.close();
            p.close();

            // Yarn Count ও Qty (একাধিক হলে প্রথমটা)
            p = con.prepareStatement("SELECT TOP 1 YarnCount, Qty FROM tblWorkOrderDetail WHERE WorkOrderNo=? ORDER BY SL");
            p.setString(1, sel(cboWorkOrder));
            r = p.executeQuery();
            if (r.next()) {
                txtYarnCount.setText(r.getString("YarnCount"));
                txtYarnQty.setText(r.getString("Qty"));
            }
            r.close();
            p.close();

            // Already Req = আগের সব requisition এর Req Qty যোগফল
            p = con.prepareStatement("SELECT ISNULL(SUM(CAST(ReqQty AS FLOAT)),0) AS Tot FROM tblCottonRequisitionDetail WHERE WorkOrder=?");
            p.setString(1, sel(cboWorkOrder));
            r = p.executeQuery();
            if (r.next()) {
                txtAlreadyReq.setText(String.format("%.2f", r.getDouble("Tot")));
            }
            r.close();
            p.close();

            CalcLoss();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboWorkOrderPopupMenuWillBecomeInvisible

