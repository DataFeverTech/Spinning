    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblCottonRequisition "
                + "(ReqId, ReqDate, Department, RequiredDate, RequestedBy, Store, Shift, Remarks, TotalRequisition) "
                + "VALUES (?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtReqId.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, selOrEmpty(cboDepartment));
        p.setDate(4, sqlDate(dtReqDate));
        p.setString(5, selOrEmpty(cboRequestedBy));
        p.setString(6, selOrEmpty(cboStore));
        p.setString(7, selOrEmpty(cboShift));
        p.setString(8, txtRemarks.getText());
        p.setString(9, txtTotalBales.getText());
        p.executeUpdate();
        p.close();
    }

    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblCottonRequisitionDetail "
                + "(ReqId, SL, WorkOrder, Buyer, YarnCount, YarnQty, Loss, CottonReq, ReqQty, ApproxBales) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblRequistionForCotton.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtReqId.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            for (int c = 1; c <= 8; c++) {
                p.setString(c + 2, String.valueOf(model.getValueAt(i, c)));
            }
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }
