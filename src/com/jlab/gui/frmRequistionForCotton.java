    private void CalcLoss() {
        double yarn = num(txtYarnQty.getText());
        double loss = num(txtProcessLoss.getText());
        double cotton = loss >= 100 ? 0 : yarn / (1 - loss / 100.0);
        txtCottonReq.setText(String.format("%.2f", cotton));
        txtBalance.setText(String.format("%.2f", cotton - num(txtAlreadyReq.getText())));
    }

