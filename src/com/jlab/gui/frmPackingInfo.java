    private void tblPackingMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPackingMouseClicked

        if (evt.getClickCount() == 2) {
            int row = tblPacking.getSelectedRow();
            if (row < 0) {
                return;
            }
            try {
                pst = con.prepareStatement("select * from tblPacking where PackingID=?");
                pst.setString(1, tblPacking.getValueAt(row, 0).toString());
                rs = pst.executeQuery();
                if (rs.next()) {
                    txtPackingId.setText(rs.getString("PackingID"));
                    txtPackingName.setText(rs.getString("PackingName"));
                    btnSave.setEnabled(false);
                    btnUpdate.setEnabled(true);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, e);
            }
        }

    }//GEN-LAST:event_tblPackingMouseClicked

