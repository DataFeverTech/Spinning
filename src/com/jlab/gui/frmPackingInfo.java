    private boolean isDuplicate(String name, String id) {
        try {
            pst = con.prepareStatement("select count(*) from tblPacking where PackingName=? and PackingID<>?");
            pst.setString(1, name);
            pst.setString(2, id);
            ResultSet r = pst.executeQuery();
            r.next();
            return r.getInt(1) > 0;
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
            return true;
        }
    }

    public void fillTable() {
        DefaultTableModel model = (DefaultTableModel) tblPacking.getModel();
        model.setRowCount(0);
        try {
            pst = con.prepareStatement("select PackingID, PackingName from tblPacking where PackingName like ? order by PackingID");
            pst.setString(1, "%" + txtSearch.getText().trim() + "%");
            ResultSet r = pst.executeQuery();
            while (r.next()) {
                model.addRow(new Object[]{r.getString("PackingID"), r.getString("PackingName")});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(PackingID) AS MaxID FROM tblPacking");
            r.next();
            String max = r.getString("MaxID");
            if (max == null) {
                txtPackingId.setText("PK-00001");
            } else {
                long id = Long.parseLong(max.substring(3));
                id++;
                txtPackingId.setText("PK-" + String.format("%05d", id));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

