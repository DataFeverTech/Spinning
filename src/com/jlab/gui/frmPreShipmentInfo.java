    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        if (txtRate.getText().trim().isEmpty() || txtPCValue.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill Rate and P.C Value");
            return;
        }

        try {
            date = dtPCDate.getDate();
            pcDate = new java.sql.Date(date.getTime());

            date = dtExpiryDate.getDate();
            expDate = new java.sql.Date(date.getTime());

            String query = "insert into tblPreShipmentInfo(PCNo,PCDate,Rate,RateUnit,ExportLC,FileNo,PCValue,Percentage,ExpiryDate) values (?,?,?,?,?,?,?,?,?)";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, txtPCNo.getText());
            pst.setDate(2, pcDate);
            pst.setString(3, txtRate.getText());
            pst.setString(4, cboRateUnit.getSelectedItem().toString());
            pst.setString(5, cboExportLC.getSelectedItem().toString());
            pst.setString(6, txtFileNo.getText());
            pst.setString(7, txtPCValue.getText());
            pst.setString(8, txtPercentage.getText());
            pst.setDate(9, expDate);

            pst.execute();
            JOptionPane.showMessageDialog(this, "Registration Successfully Completed");
            Reset();
            fillTable();
            GenAutoID();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

