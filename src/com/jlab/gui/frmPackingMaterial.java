    public ArrayList<ReadyGarments_Bean> getAllData() {
        ArrayList<ReadyGarments_Bean> al = null;
        al = new ArrayList<ReadyGarments_Bean>();
        try {

            String qry = "select * from tblPackingMaterial";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            ReadyGarments_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new ReadyGarments_Bean(rs.getString("ProdID"),
                        rs.getString("ProdName"), rs.getString("ProdHead"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void fillTable() {
        ArrayList<ReadyGarments_Bean> al = getAllData();
        DefaultTableModel model = (DefaultTableModel) tblPackingMaterial.getModel();
        //  tblChequeDetails.getColumnModel().getColumn(0).setPreferredWidth(10);
        model.setRowCount(0); // Empty/clear the table
        Object[] row = new Object[3];
        for (int i = 0; i < al.size(); i++) {
            row[0] = al.get(i).getId();
            row[1] = al.get(i).getName();
            row[2] = al.get(i).getHead();
            model.addRow(row);

        }
    }

