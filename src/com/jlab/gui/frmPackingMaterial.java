    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(ProdID) AS MaxID FROM tblPackingMaterial");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtProdID.setText("FBI-00001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtProdID.setText("FBI-" + String.format("%05d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

