    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

        int row = tblPackingMaterial.getSelectedRow();
        if (row > -1) {
            int opt = JOptionPane.showConfirmDialog(null, "Are You sure to Delete", "Delete", JOptionPane.YES_NO_OPTION);
            if (opt == 0) {
                try {
                    String value = tblPackingMaterial.getModel().getValueAt(row, 0).toString();
                    String query = "DELETE FROM tblPackingMaterial WHERE ProdID=?";
                    pst = (PreparedStatement) con.prepareStatement(query);
                    pst.setString(1, value);
                    pst.execute();
                    JOptionPane.showMessageDialog(null, "Deleted Successfully");
                    DefaultTableModel model = (DefaultTableModel) tblPackingMaterial.getModel();
                    model.setRowCount(0);
                    Reset();
                    fillTable();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(rootPane, e);
                }
            } else {
                DefaultTableModel model = (DefaultTableModel) tblPackingMaterial.getModel();
                model.setRowCount(0);
                fillTable();
            }
        } else {
            JOptionPane.showMessageDialog(null, "Please Select an Item to Delete");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased

        ArrayList<ReadyGarments_Bean> al = new ArrayList<ReadyGarments_Bean>();
        String val = txtSearch.getText().toString();
        try {
            String qry = "SELECT * FROM tblPackingMaterial WHERE ProdName LIKE ?";
            pst = (PreparedStatement) con.prepareStatement(qry);
            pst.setString(1, "%" + val + "%");
            ResultSet rs = pst.executeQuery();

            DefaultTableModel model = (DefaultTableModel) tblPackingMaterial.getModel();
            model.setRowCount(0);

            while (rs.next()) {
                Object[] row = new Object[3];
                row[0] = rs.getString("ProdID");
                row[1] = rs.getString("ProdName");
                model.addRow(row);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error at searchKeyReleased " + e);
        }

    }//GEN-LAST:event_txtSearchKeyReleased

    private void tblPackingMaterialMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPackingMaterialMouseClicked

        if (evt.getClickCount() == 2) {
            btnUpdate.setEnabled(true);
            btnSave.setEnabled(false);
            int row = tblPackingMaterial.getSelectedRow();
            try {
                String Table_click = (tblPackingMaterial.getModel().getValueAt(row, 0).toString());
                String query = "SELECT * FROM tblPackingMaterial WHERE ProdID=?";
                pst = (PreparedStatement) con.prepareStatement(query);
                pst.setString(1, Table_click);
                rs = pst.executeQuery();
                if (rs.next()) {
                    txtProdID.setText(rs.getString("ProdID"));
                    cboUnit.setSelectedItem(rs.getString("Unit"));
                    txtProdName.setText(rs.getString("ProdName"));
                    txtPacking.setText(rs.getString("PackingUnit"));
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_tblPackingMaterialMouseClicked

