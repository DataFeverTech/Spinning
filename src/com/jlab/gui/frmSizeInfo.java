    //show / add the the data to table
    public ArrayList<Size_Bean> getAllData() {
        ArrayList<Size_Bean> al = null;
        al = new ArrayList<Size_Bean>();
        try {

            String qry = "select * from tblSizeInfo";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            Size_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new Size_Bean(rs.getString("SizeID"),rs.getString("SizeName"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void fillTable() {
        ArrayList<Size_Bean> al = getAllData();
        DefaultTableModel model = (DefaultTableModel) tblSize.getModel();
        //  tblChequeDetails.getColumnModel().getColumn(0).setPreferredWidth(10);
        model.setRowCount(0); // Empty/clear the table
        Object[] row = new Object[2];
        for (int i = 0; i < al.size(); i++) {
            row[0] = al.get(i).getId();
            row[1] = al.get(i).getName();          
            model.addRow(row);

        }
    }

    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(SizeID) AS MaxID FROM tblSizeInfo");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtSizeID.setText("SZ-001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(3, rs.getString("MaxID").length()));
                id++;
                txtSizeID.setText("SZ-" + String.format("%03d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

