    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

        int row = tblSize.getSelectedRow();
        if (row > -1) {
            int opt = JOptionPane.showConfirmDialog(null, "Are You sure to Delete", "Delete", JOptionPane.YES_NO_OPTION);
            if (opt == 0) {
                try {

                    String value = tblSize.getModel().getValueAt(row, 0).toString();
                    String query = "delete from tblSizeInfo where SizeID=?";
                    pst = (PreparedStatement) con.prepareStatement(query);
                    pst.setString(1, value);
                    pst.execute();
                    JOptionPane.showMessageDialog(null, "Deleted  success");
                    DefaultTableModel model = (DefaultTableModel) tblSize.getModel();
                    model.setRowCount(0);
                    Reset();
                    fillTable();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(rootPane, e);
                }
            } else {
                DefaultTableModel model = (DefaultTableModel) tblSize.getModel();
                model.setRowCount(0);
                fillTable();
            }
        } else {

            JOptionPane.showMessageDialog(null, "Pls Selected Deleted Item");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased

        ArrayList<Unit_Bean> al = null;
        al = new ArrayList<Unit_Bean>();
        String val = txtSearch.getText().toString();

        try {

            String qry = "select * from tblSizeInfo where SizeName like '%" + val + "%'";
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery(qry);
            Unit_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new Unit_Bean(rs.getString("SizeID"),rs.getString("SizeName"));
                al.add(LoadTable);
            }

            //search ed teachers to be added to datatable
            DefaultTableModel model = (DefaultTableModel) tblSize.getModel();
            model.setRowCount(0); // Empty/clear the table
            Object[] row = new Object[2];
            for (int i = 0; i < al.size(); i++) {
                row[0] = al.get(i).getUnitId();
                row[1] = al.get(i).getUnit();         
                model.addRow(row);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error at searchKeyReleased " + e);
        }


    }//GEN-LAST:event_txtSearchKeyReleased

