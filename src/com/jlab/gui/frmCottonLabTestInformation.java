// ---------- ID ----------
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(ReceiveId) AS MaxID FROM tblCottonLabTest");
            r.next();
            if (r.getString("MaxID") == null) {
                txtReceiveId.setText("CLT-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(4));
                id++;
                txtReceiveId.setText("CLT-" + String.format("%07d", id));
            }
            txtReceiveId.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

