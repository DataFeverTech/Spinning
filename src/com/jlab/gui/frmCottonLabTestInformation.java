    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblCottonLabTest "
                + "(ReceiveId, TestDate, WorkOrder, Party, YarnCount, YarnQty, Machine, TestedBy, "
                + "RSMic, RSStaple, RSStrength, RSUI, Remarks, AvgMic, AvgStaple, AvgStrength, AvgUI) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtReceiveId.getText());
        p.setDate(2, sqlDate(dtDate));
        p.setString(3, notSel(cboWorkOrder) ? "" : sel(cboWorkOrder));
        p.setString(4, txtParty.getText());
        p.setString(5, notSel(cboYarnCount) ? "" : sel(cboYarnCount));
        p.setString(6, txtYarnQty.getText());
        p.setString(7, notSel(cboMachine) ? "" : sel(cboMachine));
        p.setString(8, notSel(cboTestedBy) ? "" : sel(cboTestedBy));
        p.setString(9, txtRSMic.getText());
        p.setString(10, txtRSStaple.getText());
        p.setString(11, txtRSStrength.getText());
        p.setString(12, txtRSUI.getText());
        p.setString(13, txtRemarks.getText());
        p.setString(14, txtTotalMic.getText());
        p.setString(15, txtTotaStaple.getText());
        p.setString(16, txtTotalStrength.getText());
        p.setString(17, txtTotalUI.getText());
        p.executeUpdate();
        p.close();
    }

    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblCottonLabTestDetail "
                + "(ReceiveId, SL, LotNo, Origin, Sample, Mic, Staple, Strength, UI, SFC, Rd, PlusB, Trash, Moisture, Result, ImportLC, AvlBales) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblCottonLabTestInformation.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtReceiveId.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            for (int c = 1; c <= 15; c++) {
                p.setString(c + 2, String.valueOf(model.getValueAt(i, c)));
            }
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }
    // ---------- Helpers ----------

    private double num(String s) {
        try {
            return Double.parseDouble(s.trim());
        } catch (Exception e) {
            return 0;
        }
    }

    private java.sql.Date sqlDate(com.toedter.calendar.JDateChooser dc) {
        return dc.getDate() == null ? null : new java.sql.Date(dc.getDate().getTime());
    }

    private String sel(javax.swing.JComboBox<String> c) {
        Object o = c.getSelectedItem();
        return o == null ? "" : o.toString();
    }

    private boolean notSel(javax.swing.JComboBox<String> c) {
        String s = sel(c);
        return s.equals("") || s.startsWith("Select");
    }

// ---------- Fill Combo ----------
    private void FillCombo(javax.swing.JComboBox<String> cbo, String query, String col) {
        try {
            cbo.removeAllItems();
            cbo.addItem("Select Product Info");
            PreparedStatement p = con.prepareStatement(query);
            ResultSet r = p.executeQuery();
            while (r.next()) {
                cbo.addItem(r.getString(col));
            }
            r.close();
            p.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

