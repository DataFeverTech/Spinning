// ---------- Grid Add ----------
    public void GridAdd() {
        if (notSel(cboLotNo)) {
            JOptionPane.showMessageDialog(this, "Select Lot No");
            return;
        }
        if (txtMic.getText().trim().isEmpty() || txtStaple.getText().trim().isEmpty()
                || txtStrength.getText().trim().isEmpty() || txtUI.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Mic, Staple, Strength & UI");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblCottonLabTestInformation.getModel();
        model.addRow(new Object[]{
            model.getRowCount() + 1,
            sel(cboLotNo),
            txtOrigin.getText(),
            txtSampleBales.getText(),
            txtMic.getText(),
            txtStaple.getText(),
            txtStrength.getText(),
            txtUI.getText(),
            txtSFC.getText(),
            txtRd.getText(),
            txt_B.getText(),
            txtTrash.getText(),
            txtMoisture.getText(),
            sel(cboResult),
            txtImportLC.getText(),
            txtAvlBales.getText()
        });

        CalcTotal();
        ClearProductFields();
    }

