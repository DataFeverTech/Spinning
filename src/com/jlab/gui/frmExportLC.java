    public void MultipleCost() {

        String rawAmountQty = txtQty.getText();
        String rawAmountMrp = txtUnitPrice.getText();

        //  int qty = Integer.parseInt(rawAmountQty);
        Double qty = Double.parseDouble(rawAmountQty);
        Double unitPrice = Double.parseDouble(rawAmountMrp);
        //     Double total = units * unitPrice;
        //    txtAmount.setText("" + total);

        DecimalFormat df = new DecimalFormat("#.00");
        txtTotalValue.setText((df.format(qty * unitPrice)));

    }

    public void percentic() {

        String rawTotalSale = txtValue.getText();
        String rawTotalPaid = txtBBPercent.getText();

        Integer sale = Integer.parseInt(rawTotalSale);
        Integer paid = Integer.parseInt(rawTotalPaid);

        Integer total = (sale * paid / 100);

        txtBBTotal.setText("" + total);

    }

