    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        try {
            con.setAutoCommit(false);

            SubmitLC();
            SubmitLCProduct();

            con.commit();
            JOptionPane.showMessageDialog(this, "Export L/C Saved Successfully");
            Reset();
        } catch (Exception e) {
            try {
                con.rollback();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Rollback Failed: " + ex.getMessage());
            }
            JOptionPane.showMessageDialog(this, "Save Failed: " + e.getMessage());
        } finally {
            try {
                con.setAutoCommit(true);
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage());
            }
        }

    }//GEN-LAST:event_btnSaveActionPerformed

    public void SubmitLC() throws Exception {

        int fob = 1;
        int cnf = 1;

        date = dtExport.getDate();
        Exldate = new java.sql.Date(date.getTime());

        String date1 = ((JTextField) dtShipment.getDateEditor().getUiComponent()).getText();
        String date2 = ((JTextField) dtValidity.getDateEditor().getUiComponent()).getText();
        String query = "Insert into tblExportLC(FileNo,Shipment,Validity,ExportLC,ExportDate,BuyerName,Fob,Cnf,ShipmentAmt,Qty,Unit,Value,Rate,BBPer,BBTotal,BankName,Remarks) values (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";

        PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);

        pst.setString(1, txtFileNo.getText());
        pst.setString(2, date1);
        pst.setString(3, date2);
        pst.setString(4, txtExportLC.getText());
        pst.setDate(5, Exldate);
        pst.setString(6, cbobuyerName.getSelectedItem().toString());
        if (rdoFob.isSelected() == true) {
            fob = 0;
        } else {
            fob = 1;
        }
        if (rdoCnf.isSelected() == true) {
            cnf = 0;
        } else {
            cnf = 1;
        }
        pst.setInt(7, fob);
        pst.setInt(8, cnf);
        pst.setString(9, txtShipmentAmt.getText());
        pst.setString(10, txtQuantity.getText());
        pst.setString(11, cboUnit.getSelectedItem().toString());
        pst.setString(12, txtValue.getText());
        pst.setString(13, txtRate.getText());
        pst.setString(14, txtBBPercent.getText());
        pst.setString(15, txtBBTotal.getText());
        pst.setString(16, cboBankName.getSelectedItem().toString());
        pst.setString(17, txtRemarks.getText());
        pst.executeUpdate();
    }

    public void SubmitLCProduct() throws Exception {

        int rows = tblExportLC.getRowCount();
        String query = "Insert into tblExportLCProduct(FileNo,JobOrder,Garments,Quantity,Unit,Price,TotalValue,BFCom,BICom) values (?,?,?,?,?,?,?,?,?)";
        PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
        for (int row = 0; row < rows; row++) {

            String JobOrder = (String) tblExportLC.getValueAt(row, 0);
            String Garments = (String) tblExportLC.getValueAt(row, 1);
            String Quantity = (String) tblExportLC.getValueAt(row, 2);
            String Unit = (String) tblExportLC.getValueAt(row, 3);
            String Price = (String) tblExportLC.getValueAt(row, 4);
            String TotalValue = (String) tblExportLC.getValueAt(row, 5);
            String BFCom = (String) tblExportLC.getValueAt(row, 6);
            String BICom = (String) tblExportLC.getValueAt(row, 7);

            pst.setString(1, txtFileNo.getText());
            pst.setString(2, JobOrder);
            pst.setString(3, Garments);
            pst.setString(4, Quantity);
            pst.setString(5, Unit);
            pst.setString(6, Price);
            pst.setString(7, TotalValue);
            pst.setString(8, BFCom);
            pst.setString(9, BICom);

            pst.addBatch();
        }
        pst.executeBatch();
    }


