    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int che = 1;
        int exp = 1;
        int imp = 1;
        int main = 1;
        int rep = 1;

        try {
            String value = userid;
            // String value = lblID.getText();
            String query = "update tblUserInfo set  chkBasic=? ,chkExp=? , chkImp=?, chkMain=?, chkReport=? where UserID='" + value + "'";
            pst = (PreparedStatement) con.prepareStatement(query);

            if (chkBasic.isSelected() == true) {
                che = 0;
            } else {
                che = 1;
            }
            if (chkExport.isSelected() == true) {
                exp = 0;
            } else {
                exp = 1;
            }
            if (chkImport.isSelected() == true) {
                imp = 0;
            } else {
                imp = 1;
            }
            if (chkMaintenace.isSelected() == true) {
                main = 0;
            } else {
                main = 1;
            }
            if (chkReport.isSelected() == true) {
                rep = 0;
            } else {
                rep = 1;
            }

            pst.setInt(1, che);
            pst.setInt(2, exp);
            pst.setInt(3, imp);
            pst.setInt(4, main);
            pst.setInt(5, rep);
            pst.execute();

            JOptionPane.showMessageDialog(this, "Updated Successfully Compled");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
        //clear the fields
    }//GEN-LAST:event_btnUpdateActionPerformed

