    private void tblUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUserMouseClicked
        if (evt.getClickCount() == 1) {
            try {
                chkBasic.setSelected(false);
                chkExport.setSelected(false);
                chkImport.setSelected(false);
                chkMaintenace.setSelected(false);
                chkReport.setSelected(false);

                int row = tblUser.getSelectedRow();

                String Table_click = (tblUser.getModel().getValueAt(row, 0).toString());
                String query = "SELECT * FROM tblUserInfo WHERE userid='" + Table_click + "' ";
                pst = (PreparedStatement) con.prepareStatement(query);
                rs = pst.executeQuery();
                if (rs.next()) {

                    String add1 = rs.getString("userid");
                    //    lblID.setText(add1);
                    userid = add1;

                    if ("0".equals(rs.getString("chkBasic"))) {

                        chkBasic.setSelected(true);

                    } else if ("1".equals(rs.getString("chkBasic"))) {
                        chkBasic.setSelected(false);
                    }
                    if ("0".equals(rs.getString("chkExp"))) {

                        chkExport.setSelected(true);

                    } else if ("1".equals(rs.getString("chkExp"))) {
                        chkExport.setSelected(false);
                    }
                    if ("0".equals(rs.getString("chkImp"))) {

                        chkImport.setSelected(true);

                    } else if ("1".equals(rs.getString("chkImp"))) {
                        chkImport.setSelected(false);
                    }
                    if ("0".equals(rs.getString("chkMain"))) {

                        chkMaintenace.setSelected(true);

                    } else if ("1".equals(rs.getString("chkMain"))) {
                        chkMaintenace.setSelected(false);
                    }
                    if ("0".equals(rs.getString("chkReport"))) {

                        chkReport.setSelected(true);

                    } else if ("1".equals(rs.getString("chkReport"))) {
                        chkReport.setSelected(false);
                    }
                }

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e);
            }
        }
    }//GEN-LAST:event_tblUserMouseClicked

    //show / add the the data to table
    public ArrayList<User_Bean> getAllData() {
        ArrayList<User_Bean> al = null;
        al = new ArrayList<User_Bean>();
        try {

            String qry = "select * from tblUserInfo";
            Statement pst = con.createStatement();
            ResultSet rs = pst.executeQuery(qry);
            User_Bean LoadTable;
            while (rs.next()) {
                LoadTable = new User_Bean(rs.getString("UserID"),
                        rs.getString("Username"), rs.getString("Des"));

                al.add(LoadTable);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error in getAllTeacherData()" + e);
            return al;
        }
        return al;
    }

    //fill the jTable1 with data
    public void fillTable() {
        ArrayList<User_Bean> al = getAllData();
        DefaultTableModel model = (DefaultTableModel) tblUser.getModel();
        model.setRowCount(0); // Empty/clear the table
        Object[] row = new Object[3];
        for (int i = 0; i < al.size(); i++) {
            row[0] = al.get(i).getUserid();
            row[1] = al.get(i).getUser();

            row[2] = al.get(i).getDescri();

            model.addRow(row);
        }
    }


