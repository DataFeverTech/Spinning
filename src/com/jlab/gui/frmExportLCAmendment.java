    public void GenAutoID() {

        try {
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(unitId) AS MaxID FROM tblunitmeas");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtExportLCID.setText("ELC-0000001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtExportLCID.setText( "ELC-" + String.format("%07d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

    
      public void ShowLocal() {

        Calendar ca = new GregorianCalendar();
        String day = ca.get(Calendar.DAY_OF_MONTH) + "";
        String month = ca.get(Calendar.MONTH) + 1 + "";
        String year = ca.get(Calendar.YEAR) + "";

        if (day.length() == 1) {
            day = "0" + day;
        }
        if (month.length() == 1) {
            month = "0" + month;
        }

        String dd = day + " " + month + " " + year;
        Date date = null;
        try {
            date = new SimpleDateFormat("dd MM yyyy").parse(dd);
        } catch (ParseException ex) {
           
        }
        dtExport.setDate(date);
        dtShipment.setDate(date);
        dtValidity.setDate(date);

    }

      
