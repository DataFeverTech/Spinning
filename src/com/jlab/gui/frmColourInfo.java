    private void tblProcessMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProcessMouseClicked

        if (evt.getClickCount() == 2) {
            int row = tblProcess.getSelectedRow();
            if (row < 0) {
                return;
            }
            try {
                pst = con.prepareStatement("select * from tblProcess where ProcessID=?");
                pst.setString(1, tblProcess.getValueAt(row, 0).toString());
                rs = pst.executeQuery();
                if (rs.next()) {
                    txtProcessID.setText(rs.getString("ProcessID"));
                    txtProcessName.setText(rs.getString("ProcessName"));
                    btnSave.setEnabled(false);
                    btnUpdate.setEnabled(true);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, e);
            }
        }

    }//GEN-LAST:event_tblProcessMouseClicked

