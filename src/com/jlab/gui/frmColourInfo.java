    private boolean isDuplicate(String name, String id) {
        try {
            pst = con.prepareStatement("select count(*) from tblProcess where ProcessName=? and ProcessID<>?");
            pst.setString(1, name);
            pst.setString(2, id);
            ResultSet r = pst.executeQuery();
            r.next();
            return r.getInt(1) > 0;
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
            return true;
        }
    }

    public void fillTable() {
        DefaultTableModel model = (DefaultTableModel) tblProcess.getModel();
        model.setRowCount(0);
        try {
            pst = con.prepareStatement("select ProcessID, ProcessName from tblProcess where ProcessName like ? order by ProcessID");
            pst.setString(1, "%" + txtSearch.getText().trim() + "%");
            ResultSet r = pst.executeQuery();
            while (r.next()) {
                model.addRow(new Object[]{r.getString("ProcessID"), r.getString("ProcessName")});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(ProcessID) AS MaxID FROM tblProcess");
            r.next();
            String max = r.getString("MaxID");
            if (max == null) {
                txtProcessID.setText("PR-00001");
            } else {
                long id = Long.parseLong(max.substring(3));
                id++;
                txtProcessID.setText("PR-" + String.format("%05d", id));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }

