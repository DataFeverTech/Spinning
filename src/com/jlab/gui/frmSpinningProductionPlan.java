    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        if (tblSpinningProductionPlan.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Please add at least one Product row");
            return;
        }

        try {
            con.setAutoCommit(false);

            SaveGeneral();
            SaveProducts();

            con.commit();
            JOptionPane.showMessageDialog(this, "Registration Successfully Completed");
            Reset();

        } catch (Exception e) {
            try {
                con.rollback();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(null, ex);
            }
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                con.setAutoCommit(true);
            } catch (Exception ex) {
            }
        }

    }//GEN-LAST:event_btnSaveActionPerformed
    private void SaveGeneral() throws Exception {
        String sql = "INSERT INTO tblSpinningPlanGeneral "
                + "(PlanNo, PlanDate, WorkOrder, Party, DeliveryDate, DayLeft, PlannedBy, Loss, Remarks, TotalYarn, TotalCotton) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        p.setString(1, txtPlanNo.getText());
        p.setDate(2, sqlDate(dtPlanDate));
        p.setString(3, sel(cboWorkOrder));
        p.setString(4, txtParty.getText());
        p.setDate(5, sqlDate(dtDeliveryDate));
        p.setString(6, txtDayLeft.getText());
        p.setString(7, sel(cboPlannedBy));
        p.setString(8, txtLoss.getText());
        p.setString(9, txtRemarks.getText());
        p.setString(10, txtTotalYarn.getText());
        p.setString(11, txtTotalCottonDay.getText());
        p.executeUpdate();
        p.close();
    }

    private void SaveProducts() throws Exception {
        String sql = "INSERT INTO tblSpinningPlanMachine "
                + "(PlanNo, SL, YarnCount, Machine, Capacity, PlanQty, StartDate, EndDate, Days, YarnDays, CottonDays, Status, YarnQty, Instruction) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        PreparedStatement p = con.prepareStatement(sql);
        DefaultTableModel model = (DefaultTableModel) tblSpinningProductionPlan.getModel();
        SimpleDateFormat f = new SimpleDateFormat("dd-MM-yyyy");

        for (int i = 0; i < model.getRowCount(); i++) {
            p.setString(1, txtPlanNo.getText());
            p.setInt(2, Integer.parseInt(model.getValueAt(i, 0).toString()));
            p.setString(3, model.getValueAt(i, 1).toString());
            p.setString(4, model.getValueAt(i, 2).toString());
            p.setString(5, model.getValueAt(i, 3).toString());
            p.setString(6, model.getValueAt(i, 4).toString());
            p.setDate(7, new java.sql.Date(f.parse(model.getValueAt(i, 5).toString()).getTime()));
            p.setDate(8, new java.sql.Date(f.parse(model.getValueAt(i, 6).toString()).getTime()));
            p.setString(9, model.getValueAt(i, 7).toString());
            p.setString(10, model.getValueAt(i, 8).toString());
            p.setString(11, model.getValueAt(i, 9).toString());
            p.setString(12, model.getValueAt(i, 10).toString());
            p.setString(13, model.getValueAt(i, 11).toString());
            p.setString(14, model.getValueAt(i, 12).toString());
            p.addBatch();
        }
        p.executeBatch();
        p.close();
    }
