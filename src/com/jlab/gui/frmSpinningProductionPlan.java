    // ---------- Grid Add ----------
    public void GridAdd() {
        if (sel(cboYarnCount).equals("") || sel(cboYarnCount).equals("Select Product Info")) {
            JOptionPane.showMessageDialog(this, "Select Yarn Count");
            return;
        }
        if (sel(cboMachine).equals("") || sel(cboMachine).equals("Select Product Info")) {
            JOptionPane.showMessageDialog(this, "Select Machine");
            return;
        }
        if (txtPlanQty.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter Plan Qty");
            return;
        }
        if (dtStartDate.getDate() == null || dtEndDate.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Select Start & End Date");
            return;
        }

        DefaultTableModel model = (DefaultTableModel) tblSpinningProductionPlan.getModel();
        model.addRow(new Object[]{
            model.getRowCount() + 1,
            sel(cboYarnCount),
            sel(cboMachine),
            txtCapacity.getText(),
            txtPlanQty.getText(),
            fmt(dtStartDate),
            fmt(dtEndDate),
            txtDays.getText(),
            txtYarnDays.getText(),
            txtCottonDay.getText(),
            "Pending",
            txtYarnQty.getText(),
            txtInstruction.getText()
        });

        CalcTotal();
        ClearMachineFields();
    }

    private void ClearMachineFields() {
        cboYarnCount.setSelectedIndex(0);
        cboMachine.setSelectedIndex(0);
        txtYarnQty.setText("");
        txtCapacity.setText("");
        txtPlanQty.setText("");
        dtStartDate.setDate(null);
        dtEndDate.setDate(null);
        txtDays.setText("");
        txtYarnDays.setText("");
        txtCottonDay.setText("");
        txtInstruction.setText("");
    }

    private void CalcTotal() {
        DefaultTableModel model = (DefaultTableModel) tblSpinningProductionPlan.getModel();
        double yarn = 0, cotton = 0;
        for (int i = 0; i < model.getRowCount(); i++) {
            yarn += num(String.valueOf(model.getValueAt(i, 11)));
            cotton += num(String.valueOf(model.getValueAt(i, 9)));
        }
        txtTotalYarn.setText(String.valueOf(yarn));   // Total Yarn
        txtTotalCottonDay.setText(String.valueOf(cotton)); // Cotton/Days
    }

    private void Reset() {
        cboWorkOrder.setSelectedIndex(0);
        cboPlannedBy.setSelectedIndex(0);
        txtParty.setText("");
        dtDeliveryDate.setDate(null);
        txtDayLeft.setText("");
        txtLoss.setText("");
        txtRemarks.setText("");
        txtTotalYarn.setText("");
        txtTotalCottonDay.setText("");
        ClearMachineFields();
        ((DefaultTableModel) tblSpinningProductionPlan.getModel()).setRowCount(0);
        GenAutoID();
        ShowLocal();
    }


