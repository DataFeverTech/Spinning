    // ---------- Helpers ----------
    private double num(String s) {
        try {
            return Double.parseDouble(s.trim());
        } catch (Exception e) {
            return 0;
        }
    }

    private java.sql.Date sqlDate(com.toedter.calendar.JDateChooser dc) {
        return dc.getDate() == null ? null : new java.sql.Date(dc.getDate().getTime());
    }

    private String sel(javax.swing.JComboBox<String> c) {
        Object o = c.getSelectedItem();
        return o == null ? "" : o.toString();
    }

    private String fmt(com.toedter.calendar.JDateChooser dc) {
        return dc.getDate() == null ? "" : new SimpleDateFormat("dd-MM-yyyy").format(dc.getDate());
    }

// ---------- ID ----------
    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet r = st.executeQuery("SELECT MAX(PlanNo) AS MaxID FROM tblSpinningPlanGeneral");
            r.next();
            if (r.getString("MaxID") == null) {
                txtPlanNo.setText("SPP-0000001");
            } else {
                long id = Long.parseLong(r.getString("MaxID").substring(4));
                id++;
                txtPlanNo.setText("SPP-" + String.format("%07d", id));
            }
            txtPlanNo.setEditable(false);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

