    private void txtPasswordKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPasswordKeyPressed
        String usra = txtUserName.getText();
        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {

            if (attempt < 4) {

                try {

                    String query = "select * from tblUserInfo where UserName=? and Password=? ";
                    PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
                    pst.setString(1, txtUserName.getText());
                    pst.setString(2, txtPassword.getText());
                    rs = pst.executeQuery();
                    if (rs.next()) {
                        //   JOptionPane.showMessageDialog(this, "Match  UserName Or Password!", "Login", JOptionPane.INFORMATION_MESSAGE);
                        frmDashBoard DS = new frmDashBoard();
                        DS.setVisible(true);
                        DS.username(usra);
                        DS.setExtendedState(JFrame.MAXIMIZED_BOTH);

                        this.dispose();

                        if ("0".equals(rs.getString("chkBasic"))) {

                            DS.basicMenu.setVisible(true);

                        } else if ("1".equals(rs.getString("chkBasic"))) {
                            DS.basicMenu.setVisible(false);
                        }

                        if ("0".equals(rs.getString("chkExp"))) {

                            DS.productionMenu.setVisible(true);

                        } else if ("1".equals(rs.getString("chkExp"))) {
                            DS.productionMenu.setVisible(false);
                        }

                        if ("0".equals(rs.getString("chkImp"))) {

                            DS.taskMenu.setVisible(true);

                        } else if ("1".equals(rs.getString("chkImp"))) {
                            DS.taskMenu.setVisible(false);
                        }
                        if ("0".equals(rs.getString("chkMain"))) {

                            DS.maintenMenu.setVisible(true);

                        } else if ("1".equals(rs.getString("chkMain"))) {
                            DS.maintenMenu.setVisible(false);
                        }
                        if ("0".equals(rs.getString("chkReport"))) {

                            DS.reportMenu.setVisible(true);

                        } else if ("1".equals(rs.getString("chkReport"))) {
                            DS.reportMenu.setVisible(false);
                        }

                    } else {
                        JOptionPane.showMessageDialog(this, "Incorrent UserName Or Password!" + "" + attempt, "Login Error", JOptionPane.ERROR_MESSAGE);

                    }

                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, e);
                }
            } else if (attempt != 4) {
                JOptionPane.showMessageDialog(this, "Try Once Again!" + "" + attempt, "Login Error", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Exceed!" + "" + attempt, "Login Error", JOptionPane.ERROR_MESSAGE);
                txtUserName.setEnabled(false);
                txtPassword.setEnabled(false);
            }
            if (attempt == 5) {
                this.dispose();
            }
            attempt++;

        }
    }//GEN-LAST:event_txtPasswordKeyPressed

