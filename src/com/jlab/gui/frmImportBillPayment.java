    private void Fill_InvoiceNo() {
        try {
            String query = "SELECT * FROM tblImportBillInfo ";
            PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
            rs = pst.executeQuery();
            while (rs.next()) {
                String cname = rs.getString("BillNo");

                cboInvoiceNo.addItem(cname);

            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

    private void Fill_ExportLCDetails() {
        String exportLC = txtExportLC.getText();
        if (exportLC == null || exportLC.trim().isEmpty()) {
            return;
        }
        try {
            String query = "SELECT * FROM tblExportLC WHERE ExportLC=?";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, exportLC);
            rs = pst.executeQuery();
            if (rs.next()) {
                txtFileNo.setText(rs.getString("FileNo"));
                txtBuyer.setText(rs.getString("BuyerName"));
                txtQty.setText(rs.getString("Qty"));
                txtTotalValue.setText(rs.getString("Value"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

    private void Fill_Currency() {
        try {
            String query = "SELECT CurrencyName FROM tblCurrencyInfo";
            PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
            rs = pst.executeQuery();
            while (rs.next()) {
                cboCurrency.addItem(rs.getString("CurrencyName"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

    public void GenAutoID() {
        try {
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(PayNo) AS MaxID FROM tblImportBillPayment");
            rs.next();
            if (rs.getString("MaxID") == null) {
                txtImportBillPayNo.setText("IBP-00001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtImportBillPayNo.setText("IBP-" + String.format("%05d", id));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }

    public void ShowLocal() {

        Calendar ca = new GregorianCalendar();
        String day = ca.get(Calendar.DAY_OF_MONTH) + "";
        String month = ca.get(Calendar.MONTH) + 1 + "";
        String year = ca.get(Calendar.YEAR) + "";

        if (day.length() == 1) {
            day = "0" + day;
        }
        if (month.length() == 1) {
            month = "0" + month;
        }

        String dd = day + " " + month + " " + year;
        Date date = null;
        try {
            date = new SimpleDateFormat("dd MM yyyy").parse(dd);
        } catch (ParseException ex) {

        }
        dtBill.setDate(date);

    }

