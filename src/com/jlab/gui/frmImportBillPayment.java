    private void cboInvoiceNoPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboInvoiceNoPopupMenuWillBecomeInvisible
        String selected = (String) cboInvoiceNo.getSelectedItem();
        if (selected == null || selected.equals("Select Invoice")) {
            return;
        }
        try {
            String query = "SELECT * FROM tblImportBillInfo WHERE BillNo=?";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, selected);
            rs = pst.executeQuery();
            if (rs.next()) {
                txtExportLC.setText(rs.getString("ExportLC"));
                txtImportLC.setText(rs.getString("ImportLC"));

                String maturityDateStr = rs.getString("MaturityDate");
                if (maturityDateStr != null && !maturityDateStr.isEmpty()) {
                    try {
                        Date maturityDate = new SimpleDateFormat("dd-MM-yyyy").parse(maturityDateStr);
                        dtMaturity.setDate(maturityDate);
                    } catch (ParseException ex) {
                    }
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

        Fill_ExportLCDetails();
    }//GEN-LAST:event_cboInvoiceNoPopupMenuWillBecomeInvisible

