    public void GenAutoID() {

        try {

            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("SELECT MAX(JobOrderID) AS MaxID FROM tblJobOrderInfo");
            rs.next();
            rs.getString("MaxID");
            if (rs.getString("MaxID") == null) {
                txtJobOrderID.setText("JOB-0000001");
            } else {
                long id = Long.parseLong(rs.getString("MaxID").substring(4, rs.getString("MaxID").length()));
                id++;
                txtJobOrderID.setText("JOB-" + String.format("%07d", id));
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }

