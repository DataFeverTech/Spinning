    private void lableImageMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_lableImageMouseClicked
        if (evt.getClickCount() == 2) {

            JFileChooser fileChooser = new JFileChooser();
            fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter(
                    "Image Files", "jpg", "jpeg", "png"));

            int result = fileChooser.showOpenDialog(this);
            if (result == JFileChooser.APPROVE_OPTION) {
                try {
                    File selectedFile = fileChooser.getSelectedFile();

                    String ext = selectedFile.getName().substring(selectedFile.getName().lastIndexOf('.') + 1);

                    File destDir = new File("D:\\JLab_Photos\\Comartial_Image");
                    if (!destDir.exists()) {
                        destDir.mkdirs();
                    }

                    String fileName = txtJobOrderID.getText() + "." + ext;
                    File destFile = new File(destDir, fileName);

                    java.nio.file.Files.copy(selectedFile.toPath(), destFile.toPath(),
                            java.nio.file.StandardCopyOption.REPLACE_EXISTING);

                    javax.swing.ImageIcon icon = new javax.swing.ImageIcon(
                            new javax.swing.ImageIcon(destFile.getAbsolutePath()).getImage()
                                    .getScaledInstance(lableImage.getWidth(), lableImage.getHeight(), java.awt.Image.SCALE_SMOOTH));
                    lableImage.setIcon(icon);

                    selectedImagePath = destFile.getAbsolutePath();

                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Image Save Failed: " + e.getMessage());
                }
            }
        }
    }//GEN-LAST:event_lableImageMouseClicked

