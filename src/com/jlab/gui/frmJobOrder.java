    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        try {
            con.setAutoCommit(false);

            SubmitJobOrder();
            SubmitJobColour();
            SubmitJobSize();
            SubmitJobImage();

            con.commit();
            JOptionPane.showMessageDialog(this, "Job Order Saved Successfully");
            Reset();
        } catch (Exception e) {
            try {
                con.rollback();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Rollback Failed: " + ex.getMessage());
            }
            JOptionPane.showMessageDialog(this, "Save Failed: " + e.getMessage());
        } finally {
            try {
                con.setAutoCommit(true);
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

    public void SubmitJobOrder() throws Exception {

        date = dtOrder.getDate();
        orddate = new java.sql.Date(date.getTime());

        date = dtShipment.getDate();
        shipdate = new java.sql.Date(date.getTime());

        String query = "Insert into tblJobOrderInfo(JobOrderID,BuyerName,JobOrder,OrderDate,Program,Garments,PO,Style,Qty,Unit,Price,ShipmentDate,BCOM,GSM,Weight,Productivity,Merchandiser,Remarks) values (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)";

        PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);

        pst.setString(1, txtJobOrderID.getText());
        pst.setString(2, cbobuyerName.getSelectedItem().toString());
        pst.setString(3, txtJobOrder.getText());
        pst.setDate(4, orddate);
        pst.setString(5, cboProgramName.getSelectedItem().toString());
        pst.setString(6, cboGarment.getSelectedItem().toString());
        pst.setString(7, txtPO.getText());
        pst.setString(8, txtStyle.getText());
        pst.setString(9, txtQty.getText());
        pst.setString(10, cboUnit.getSelectedItem().toString());
        pst.setString(11, txtUnitPrice.getText());
        pst.setDate(12, shipdate);
        pst.setString(13, txtBCom.getText());
        pst.setString(14, txtGSM1.getText());
        pst.setString(15, txtWeight.getText());
        pst.setString(16, txtProductivity.getText());
        pst.setString(17, cboMerchandiser.getSelectedItem().toString());
        pst.setString(18, txtRemarks.getText());
        pst.executeUpdate();
    }

    public void SubmitJobColour() throws Exception {

        int rows = tblColour.getRowCount();
        String query = "Insert into tblJobOrderColourInfo(JobOrderID,JobColourID,JobColourName) values (?,?,?)";
        PreparedStatement pst = (PreparedStatement) con.prepareStatement(query);
        for (int row = 0; row < rows; row++) {

            String Code = (String) tblColour.getValueAt(row, 0);
            String ColourName = (String) tblColour.getValueAt(row, 1);

            pst.setString(1, txtJobOrderID.getText());
            pst.setString(2, Code);
            pst.setString(3, ColourName);
            pst.addBatch();
        }
        pst.executeBatch();
    }

