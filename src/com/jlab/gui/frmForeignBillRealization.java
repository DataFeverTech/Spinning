    private void cboCurrencyPopupMenuWillBecomeInvisible(javax.swing.event.PopupMenuEvent evt) {//GEN-FIRST:event_cboCurrencyPopupMenuWillBecomeInvisible
        String currName = cboCurrency.getSelectedItem().toString();
        try {
            String query = "SELECT Realized FROM tblCurrencyInfo WHERE CurrencyName=?";
            pst = (PreparedStatement) con.prepareStatement(query);
            pst.setString(1, currName);
            rs = pst.executeQuery();
            if (rs.next()) {
                txtCurrencyRate.setText(rs.getString("Realized"));
                txtRate.setText(rs.getString("Realized"));
                calculateTotal();   // এখানে explicit call
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_cboCurrencyPopupMenuWillBecomeInvisible

