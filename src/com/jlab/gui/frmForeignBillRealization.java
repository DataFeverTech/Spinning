    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        if (tblExportLC.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Please add at least one Bank Account row");
            return;
        }

        try {
            con.setAutoCommit(false);

            SaveGeneral();
            SaveBank();

            con.commit();
            JOptionPane.showMessageDialog(this, "Registration Successfully Completed");
            ResetGeneral();
            GenAutoID();

        } catch (Exception e) {
            try {
                con.rollback();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(null, ex);
            }
            JOptionPane.showMessageDialog(null, e);
        } finally {
            try {
                con.setAutoCommit(true);
            } catch (Exception ex) {
            }
        }
    }//GEN-LAST:event_btnSaveActionPerformed
    private void SaveGeneral() throws Exception {
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String negDate = dtNagotiation.getDate() != null ? sdf.format(dtNagotiation.getDate()) : null;
        String rDate = dtRealization.getDate() != null ? sdf.format(dtRealization.getDate()) : null;

        String generalQuery = "INSERT INTO tblForeignBillRealization "
                + "(FBRID,ExportLC,ExportBill,CurrencyName,CurrencyRate,Negotiation,Realization,BillNeg,BIPercentage,NegotiationDate,RDate,FCom,Discount,Remarks) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)";
        pst = (PreparedStatement) con.prepareStatement(generalQuery);
        pst.setString(1, txtExportLCID.getText());
        pst.setString(2, cboExportLC.getSelectedItem().toString());
        pst.setString(3, cboExportBill.getSelectedItem().toString());
        pst.setString(4, cboCurrency.getSelectedItem().toString());
        pst.setDouble(5, Double.parseDouble(txtCurrencyRate.getText()));
        pst.setDouble(6, Double.parseDouble(txtNegotiation.getText()));
        pst.setDouble(7, Double.parseDouble(txtRealization.getText()));
        pst.setDouble(8, Double.parseDouble(txtValue2.getText()));
        pst.setDouble(9, Double.parseDouble(txtBIPercentage.getText()));
        pst.setString(10, negDate);
        pst.setString(11, rDate);
        pst.setDouble(12, Double.parseDouble(txtFCom.getText()));
        pst.setDouble(13, Double.parseDouble(txtDiscount.getText()));
        pst.setString(14, txtRemarks.getText());
        pst.execute();
    }

    private void SaveBank() throws Exception {
        String bankQuery = "INSERT INTO tblForeignBillRealizationBank "
                + "(FBRID,BankAccount,Percentage,ValueInDollar,Rate,TotalValue) VALUES (?,?,?,?,?,?)";
        pst = (PreparedStatement) con.prepareStatement(bankQuery);

        DefaultTableModel model = (DefaultTableModel) tblExportLC.getModel();
        for (int i = 0; i < model.getRowCount(); i++) {
            pst.setString(1, txtExportLCID.getText());
            pst.setString(2, model.getValueAt(i, 0).toString());
            pst.setDouble(3, Double.parseDouble(model.getValueAt(i, 1).toString()));
            pst.setDouble(4, Double.parseDouble(model.getValueAt(i, 2).toString()));
            pst.setDouble(5, Double.parseDouble(model.getValueAt(i, 3).toString()));
            pst.setDouble(6, Double.parseDouble(model.getValueAt(i, 4).toString()));
            pst.addBatch();
        }
        pst.executeBatch();
    }
