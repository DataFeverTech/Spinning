    private void calculateTotal() {
        try {
            double value = Double.parseDouble(txtValue.getText().trim());
            double rate = Double.parseDouble(txtRate.getText().trim());
            txtTotalValue.setText(String.valueOf(value * rate));
        } catch (NumberFormatException e) {
            txtTotalValue.setText("");
        }
    }

